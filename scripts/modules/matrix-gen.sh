#!/usr/bin/env bash
# scripts/modules/matrix-gen.sh — seed the Matrix module: secrets, Synapse's
# homeserver.yaml and Element's runtime config.
#
# Idempotent: an existing key is never rotated and an existing homeserver.yaml
# or config.json is never rewritten — a second run changes nothing, so a
# re-install cannot break a working deployment.
#
# Writes:
#   modules/matrix/.env                     POSTGRES_*, SYNAPSE_* secrets
#   $DATA_DIR/matrix/synapse/homeserver.yaml Synapse config (PostgreSQL, no TLS)
#   $DATA_DIR/matrix/synapse/log.config      Synapse logging
#   $DATA_DIR/matrix/element/config.json     Element's homeserver URL + branding
#
# The admin bot the `make matrix-*` recipes authenticate as is created by
# scripts/modules/matrix-admin.sh; its credentials live in the same .env.
set -uo pipefail
. "$(dirname "$(readlink -f "$0")")/../lib/instance.sh"

ENV="$REPO_DIR/modules/matrix/.env"
SYN="$DATA_DIR/matrix/synapse"
ELM="$DATA_DIR/matrix/element"
MAS="$DATA_DIR/matrix/mas"
mkdir -p "$SYN" "$ELM" "$MAS/keys" "$DATA_DIR/matrix/pgdata" "$DATA_DIR/matrix/mas-pgdata"
touch "$ENV"
chmod 600 "$ENV"

_seed() {  # _seed <KEY> <value>
  grep -qE "^$1=.+" "$ENV" && return 0
  printf '%s=%s\n' "$1" "$2" >>"$ENV"
  echo "matrix-gen: seeded $1" >&2
}

_seed POSTGRES_DB                         synapse
_seed POSTGRES_USER                       synapse
_seed POSTGRES_PASSWORD                   "$(openssl rand -hex 32)"
_seed SYNAPSE_REGISTRATION_SHARED_SECRET  "$(openssl rand -hex 32)"
_seed SYNAPSE_MACAROON_SECRET             "$(openssl rand -hex 64)"
_seed SYNAPSE_FORM_SECRET                 "$(openssl rand -hex 32)"
_seed SYNAPSE_ADMIN_USER                  mkadmin
_seed SYNAPSE_ADMIN_PASSWORD              "$(openssl rand -hex 24)"
# Matrix Authentication Service (ESS CE auth): its own database password, the
# secret that encrypts stored upstream data, the OAuth client secret Synapse
# authenticates with, the shared secret for MAS -> Synapse token introspection,
# and the shared secret that also authenticates MAS (and the `make matrix-*`
# recipes) to Synapse's admin API.
_seed MAS_DB_PASSWORD                     "$(openssl rand -hex 32)"
_seed MAS_ENCRYPTION_SECRET               "$(openssl rand -hex 32)"
_seed MAS_CLIENT_SECRET                   "$(openssl rand -hex 32)"
_seed MAS_SYNAPSE_SECRET                  "$(openssl rand -hex 32)"

# shellcheck disable=SC1090
. "$ENV"

if [ ! -s "$SYN/homeserver.yaml" ]; then
  cat >"$SYN/homeserver.yaml" <<YAML
# Generated by scripts/modules/matrix-gen.sh — instance state, never committed.
# The homeserver NAME is the hostname that serves the API (matrix.$DOMAIN): it is
# the suffix of every user id and of every room alias, so it is fixed for the
# life of the deployment.
server_name: "matrix.$DOMAIN"
public_baseurl: "https://matrix.$DOMAIN/"
pid_file: /data/homeserver.pid
web_client_location: "https://chat.$DOMAIN/"

listeners:
  - port: 8008
    tls: false
    type: http
    bind_addresses: ["0.0.0.0"]
    x_forwarded: true
    resources:
      - names: [client, federation]
        compress: false

database:
  name: psycopg2
  args:
    user: "$POSTGRES_USER"
    password: "$POSTGRES_PASSWORD"
    database: "$POSTGRES_DB"
    host: matrix-db
    port: 5432
    cp_min: 5
    cp_max: 10

log_config: "/data/log.config"
media_store_path: "/data/media_store"
max_upload_size: 100M
uploads_path: "/data/uploads"
enable_registration: false
registration_shared_secret: "$SYNAPSE_REGISTRATION_SHARED_SECRET"
report_stats: false
macaroon_secret_key: "$SYNAPSE_MACAROON_SECRET"
form_secret: "$SYNAPSE_FORM_SECRET"
signing_key_path: "/data/matrix.$DOMAIN.signing.key"
trusted_key_servers:
  - server_name: "matrix.org"

# Authentication is delegated to Matrix Authentication Service (ESS CE): Synapse
# keeps the data (users, rooms, media) and stops handling passwords and access
# tokens itself. Every login, registration and token refresh is served by
# auth.matrix.$DOMAIN; Synapse answers the API calls those tokens unlock and
# publishes MAS's OAuth metadata on /_matrix/client/v1/auth_metadata, which is
# how a client learns to send its user to the issuer instead of posting a
# password here.
#
# This is the ONLY delegation block: the older experimental_features.msc3861
# spelling is refused outright ("was removed. Use the
# matrix_authentication_service configuration instead"), so a config carrying
# both never starts.
#
# The shared secret is the only credential between the two: Synapse takes it as
# the bearer token on /_synapse/admin — the make matrix-* recipes and the
# installer's readiness probe present it instead of a password login, which no
# longer exists — and MAS sends the same value when it calls the homeserver.
matrix_authentication_service:
  enabled: true
  endpoint: "http://matrix-mas:8080/"
  secret: "$MAS_SYNAPSE_SECRET"

# MSC4108: the rendezvous Element's "Link new device" / "Sign in with QR code"
# uses. Its login half is MAS's device-authorization grant, which is why
# Synapse refuses the setting unless matrix_authentication_service is enabled —
# and why the old MSC3882 login-via-existing-session is refused WITH it.
experimental_features:
  msc4108_enabled: true

# No URL previews: fetching arbitrary third-party pages from this box is an
# outbound request the operator did not ask for.
url_preview_enabled: false

# Federation is on (the client-server API and federation share the edge vhost),
# but room listing stays private unless a room opts in.
allow_public_rooms_over_federation: false

rc_login:
  address:
    per_second: 0.17
    burst_count: 3
  account:
    per_second: 0.17
    burst_count: 3
  failed_attempts:
    per_second: 0.17
    burst_count: 3
YAML

  cat >"$SYN/log.config" <<'LOGCONF'
version: 1
formatters:
  precise:
    format: "%(asctime)s - %(name)s - %(lineno)d - %(levelname)s - %(request)s - %(message)s"
handlers:
  console:
    class: logging.StreamHandler
    formatter: precise
loggers:
  synapse.storage.SQL:
    level: INFO
root:
  level: INFO
  handlers: [console]
disable_existing_loggers: false
LOGCONF
  echo "matrix-gen: wrote $SYN/homeserver.yaml" >&2
fi

if [ ! -s "$ELM/config.json" ]; then
  cat >"$ELM/config.json" <<JSON
{
  "default_server_config": {
    "m.homeserver": {
      "base_url": "https://matrix.$DOMAIN",
      "server_name": "matrix.$DOMAIN"
    },
    "m.authentication": {
      "issuer": "https://auth.matrix.$DOMAIN/"
    }
  },
  "brand": "Element",
  "disable_guests": true,
  "disable_3pid_login": true,
  "show_labs_settings": false,
  "default_country_code": "GB",
  "room_directory": {
    "servers": ["matrix.$DOMAIN"]
  },
  "features": {
    "feature_login_with_qr": true
  }
}
JSON
  chmod 644 "$ELM/config.json"
  echo "matrix-gen: wrote $ELM/config.json" >&2
fi

# QR sign-in is a labs flag in this Element build and is off by default; the
# element container mounts config.json as a single file, so the flag is written
# through the existing inode (mv would leave the container on the old one).
if [ -s "$ELM/config.json" ] && [ "$(jq -r '.features.feature_login_with_qr // false' "$ELM/config.json")" != "true" ]; then
  tmp=$(mktemp)
  if jq '.features["feature_login_with_qr"] = true' "$ELM/config.json" >"$tmp"; then
    cat "$tmp" >"$ELM/config.json"
    rm -f "$tmp"
    chmod 644 "$ELM/config.json"
    echo "matrix-gen: enabled feature_login_with_qr in $ELM/config.json" >&2
  else
    rm -f "$tmp"
    echo "matrix-gen: cannot enable feature_login_with_qr in $ELM/config.json — fix the JSON and re-run" >&2
    exit 1
  fi
fi

# An install older than the MSC4108 support carries no experimental_features
# block in homeserver.yaml; append it (Synapse needs a restart to read it). An
# operator's own block is never rewritten — it gets a warning instead, so a
# second key is never planted beside theirs.
if [ -s "$SYN/homeserver.yaml" ] && ! grep -qE '^[[:space:]]*msc4108_enabled:' "$SYN/homeserver.yaml"; then
  if grep -qE '^experimental_features:' "$SYN/homeserver.yaml"; then
    echo "matrix-gen: $SYN/homeserver.yaml has its own experimental_features block — add 'msc4108_enabled: true' there and restart matrix-synapse, or QR sign-in stays off" >&2
  else
    printf '\n# MSC4108 QR sign-in ("Link new device"): needs matrix_authentication_service.\nexperimental_features:\n  msc4108_enabled: true\n' >>"$SYN/homeserver.yaml"
    echo "matrix-gen: enabled MSC4108 in $SYN/homeserver.yaml — restart matrix-synapse to apply" >&2
  fi
fi

# A config.json written before delegated auth carries no issuer, so Element
# never reads the auth metadata and falls back to the endpoints MAS removed.
# Add only that block; every other key stays the operator's.
if [ -s "$ELM/config.json" ] && ! grep -q '"m.authentication"' "$ELM/config.json"; then
  tmp=$(mktemp)
  if jq --arg issuer "https://auth.matrix.$DOMAIN/" \
      '.default_server_config["m.authentication"] = {issuer: $issuer}' \
      "$ELM/config.json" >"$tmp"; then
    # Through the existing inode: the element container bind-mounts this one
    # file, and mv would leave it serving the replaced (deleted) copy.
    cat "$tmp" >"$ELM/config.json"
    rm -f "$tmp"
    chmod 644 "$ELM/config.json"
    echo "matrix-gen: added the MAS issuer to $ELM/config.json" >&2
  else
    rm -f "$tmp"
    echo "matrix-gen: cannot add the MAS issuer to $ELM/config.json — fix the JSON and re-run" >&2
    exit 1
  fi
fi

# ── Matrix Authentication Service (ESS CE) ──────────────────────────────────
# config.yaml is written once, then owned by the operator — a re-run never
# rewrites it (same rule as homeserver.yaml). The signing keys are generated
# here because MAS mints every access token with them; they are private to the
# container's uid (65532, distroless, no shell), never world-readable.
if [ ! -s "$MAS/config.yaml" ]; then
  mkdir -p "$MAS/keys"
  [ -s "$MAS/keys/rsa.pem" ] || openssl genrsa -out "$MAS/keys/rsa.pem" 2048 2>/dev/null
  [ -s "$MAS/keys/ec.pem" ] || openssl ecparam -name prime256v1 -genkey -noout -out "$MAS/keys/ec.pem" 2>/dev/null
  chmod 600 "$MAS/keys/rsa.pem" "$MAS/keys/ec.pem"
  # MAS runs as uid 65532 (distroless, no shell): it owns the key directory and
  # the keys, so the host keeps them 0700/0600 without a world-readable copy.
  chmod 700 "$MAS/keys"
  chown 65532:65532 "$MAS" "$MAS/keys" "$MAS/keys/rsa.pem" "$MAS/keys/ec.pem" 2>/dev/null || true
  cat >"$MAS/config.yaml" <<YAML
# Generated by scripts/modules/matrix-gen.sh — instance state, never committed.
http:
  public_base: "https://auth.matrix.$DOMAIN/"
  issuer: "https://auth.matrix.$DOMAIN/"
  listeners:
    - name: web
      resources:
        - name: discovery
        - name: human
        - name: oauth
        - name: compat
        - name: graphql
        - name: assets
        # Element Admin calls /api/admin/v1 on this listener; it sends its own
        # permissive CORS headers, so the edge adds none.
        - name: adminapi
      binds:
        - address: "0.0.0.0:8080"
    - name: internal
      resources:
        - name: health
      binds:
        - host: 127.0.0.1
          port: 8081
  trusted_proxies:
    # Caddy runs with network_mode: host, so MAS sees it as the bridge gateway
    # — never trust the whole module bridge, where any container could spoof.
    - 172.22.0.1/32
    - 127.0.0.1/32
database:
  uri: "postgresql://mas:$MAS_DB_PASSWORD@matrix-mas-db/mas"
secrets:
  encryption: "$MAS_ENCRYPTION_SECRET"
  keys:
    - kid: rsa1
      key_file: /data/keys/rsa.pem
    - kid: ec1
      key_file: /data/keys/ec.pem
passwords:
  enabled: true
  schemes:
    - version: 1
      algorithm: argon2id
  minimum_complexity: 3
matrix:
  kind: synapse
  # The homeserver NAME, not its URL: MAS rejects tokens whose subject is not on
  # this server.
  homeserver: "matrix.$DOMAIN"
  secret: "$MAS_SYNAPSE_SECRET"
  endpoint: "http://matrix-synapse:8008/"
clients:
  # The OAuth client named after the homeserver. Element registers its own
  # through the registration endpoint.
  - client_id: 0000000000000000000SYNAPSE
    client_auth_method: client_secret_basic
    client_secret: "$MAS_CLIENT_SECRET"
policy:
  data:
    # Only these accounts may use the admin API that Element Admin drives.
    admin_users:
      - "@$SYNAPSE_ADMIN_USER:matrix.$DOMAIN"
YAML
  chmod 600 "$MAS/config.yaml"
  chown 65532:65532 "$MAS/config.yaml" 2>/dev/null || true
  echo "matrix-gen: wrote $MAS/config.yaml" >&2
fi

# Tighten keys written by an earlier run (they used to be 0644 root).
if [ -d "$MAS/keys" ]; then
  chmod 700 "$MAS/keys"
  chmod 600 "$MAS/keys"/*.pem 2>/dev/null || true
  chown 65532:65532 "$MAS/keys" "$MAS/keys"/*.pem 2>/dev/null || true
fi

echo "matrix-gen: module env + configs are ready"
