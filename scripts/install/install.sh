# Publish the mailserver's DKIM key as a TXT record via the Cloudflare API —
# the whole mail-authentication stack (SPF/DKIM/DMARC + PTR) then only needs
# the operator's provider-side PTR. Runs after the mailserver is up
# (containers_up); requires ENABLE_OPENDKIM=0 in the mailserver compose
# (Rspamd signs — otherwise `setup config dkim` aborts on the conflict).
dkim_setup() {
  cd "$REPO" || exit 1
  local rec value zone id i=0
  # The mailserver restart-loops until Caddy has written its mail.$DOMAIN cert
  # (SSL_TYPE=manual) — wait for a live container, or `setup config dkim`
  # aborts and the error surfaces as a bare "keygen".
  while [ $i -lt 90 ]; do
    docker exec mailserver true >/dev/null 2>&1 && break
    sleep 2; i=$((i+2))
  done
  # rc=1 when the key already exists ("Not overwriting existing files") — the
  # idempotent case, so judge by the public key, not the exit code.
  docker exec mailserver setup config dkim domain "$DOMAIN" >/dev/null 2>&1 || true
  # *.public.txt is the BIND zone-file form and splits the key across quoted
  # lines (grepping it published a truncated key); *.public.dns.txt is the
  # single-line record, ready to publish.
  rec=$(docker exec mailserver sh -c 'cat /tmp/docker-mailserver/rspamd/dkim/*.public.dns.txt' 2>/dev/null \
    | grep -oE 'p=[A-Za-z0-9+/=]+' | sed 's/p=//' | tr -d '\n')
  [ -n "$rec" ] || fail dkim_setup "no public key"
  value="v=DKIM1; k=rsa; p=$rec"
  zone=$(curl -s -H "Authorization: Bearer $CF_API_TOKEN" "https://api.cloudflare.com/client/v4/zones?name=$DOMAIN" \
    | python3 -c "import sys,json; d=json.load(sys.stdin); print(d['result'][0]['id'] if d.get('result') else '')" 2>/dev/null)
  [ -n "$zone" ] || fail dkim_setup "zone lookup"
  # drop any stale mail._domainkey TXT records, then publish ours
  for id in $(curl -s -H "Authorization: Bearer $CF_API_TOKEN" \
      "https://api.cloudflare.com/client/v4/zones/$zone/dns_records?type=TXT&name=mail._domainkey.$DOMAIN" \
      | python3 -c "import sys,json; [print(r['id']) for r in (json.load(sys.stdin).get('result') or [])]" 2>/dev/null); do
    curl -s -X DELETE -H "Authorization: Bearer $CF_API_TOKEN" \
      "https://api.cloudflare.com/client/v4/zones/$zone/dns_records/$id" >/dev/null
  done
  python3 - "$CF_API_TOKEN" "$zone" "$value" <<'EOF' || fail dkim_setup "record publish"
import sys, json, urllib.request
tok, zone, val = sys.argv[1], sys.argv[2], sys.argv[3]
req = urllib.request.Request(f"https://api.cloudflare.com/client/v4/zones/{zone}/dns_records",
  data=json.dumps({"type": "TXT", "name": "mail._domainkey", "content": val, "ttl": 1, "proxied": False}).encode(),
  headers={"Authorization": "Bearer " + tok, "Content-Type": "application/json"}, method="POST")
sys.exit(0 if json.loads(urllib.request.urlopen(req).read().decode()).get("success") else 1)
EOF
  log "DKIM published: mail._domainkey TXT for $DOMAIN (PTR remains provider-side)"
}

ssl_mode_full() {
  # API first (needs Zone Settings read on the token); fall back to a
  # behavior probe — Flexible/Off makes CF reach the origin over HTTP and
  # Caddy answers a 308 back to the same https URL (redirect loop).
  local mode hdrs code loc
  mode=$(curl -s -H "Authorization: Bearer $CF_API_TOKEN" \
    "https://api.cloudflare.com/client/v4/zones/$ZONE_ID/settings/ssl" 2>/dev/null \
    | jq -r '.result.value // empty' 2>/dev/null)
  case "$mode" in full|strict) return 0 ;; esac
  [ -n "$mode" ] && return 1
  hdrs=$(curl -sI --max-time 15 "https://cloud.$DOMAIN" 2>/dev/null | tr -d '\r')
  code=$(echo "$hdrs" | awk 'NR==1{print $2}')
  loc=$(echo "$hdrs" | awk 'tolower($1)=="location:"{print $2; exit}')
  [ "$code" = "308" ] && [[ "$loc" == *"cloud.$DOMAIN"* ]] && return 1
  return 0
}

  cf_dns() {
  VPS_IP=$(curl -s4 ifconfig.me)
  ZONE_ID=$(curl -s -H "Authorization: Bearer $CF_API_TOKEN" \
    "https://api.cloudflare.com/client/v4/zones?name=$DOMAIN" | jq -r '.result[0].id // empty')
  if [ -z "$ZONE_ID" ]; then
    fail zone
    return
  fi
  cf_record() { # $1=host $2=proxied(true/false)
    local rid
    rid=$(curl -s -H "Authorization: Bearer $CF_API_TOKEN" \
      "https://api.cloudflare.com/client/v4/zones/$ZONE_ID/dns_records?type=A&name=$1.$DOMAIN" | jq -r '.result[0].id // empty')
    if [ -z "$rid" ]; then
      curl -s -X POST -H "Authorization: Bearer $CF_API_TOKEN" -H "Content-Type: application/json" \
        "https://api.cloudflare.com/client/v4/zones/$ZONE_ID/dns_records" \
        -d "{\"type\":\"A\",\"name\":\"$1.$DOMAIN\",\"content\":\"$VPS_IP\",\"ttl\":1,\"proxied\":$2}" \
        >>"$LOG" 2>&1 || fail "dns_$1"
    fi
  }
  # proxied (orange cloud): cloud/vault/kuma/www. talk rides on the cloud door.
  for h in cloud vault kuma www; do
    case "$h" in
      cloud) [ "${MOD_CLOUD:-true}" = "true" ] && cf_record "$h" true;;
      vault) [ "${MOD_VAULT:-true}" = "true" ] && cf_record "$h" true;;
      kuma)  [ "${MOD_MONITOR:-true}" = "true" ] && cf_record "$h" true;;
      www)   cf_record "$h" true;;
    esac
  done
  # talk/mail MUST be DNS-only (grey cloud): TURN relays media over
  # UDP/TCP 3478/5349 + 49160-49200 and SMTP/IMAP also bypass the CF proxy
  # (HTTP(S) only). Caddy still gets their LE certs via DNS-01.
  [ "${MOD_CLOUD:-true}" = "true" ] && cf_record talk false
  [ "${MOD_MAIL:-true}"  = "true" ] && cf_record mail false
  curl -s -X PATCH -H "Authorization: Bearer $CF_API_TOKEN" -H "Content-Type: application/json" \
    "https://api.cloudflare.com/client/v4/zones/$ZONE_ID/settings/ssl" -d '{"value":"full"}' >>"$LOG" 2>&1 || true
  # DNS-only tokens can't set SSL mode; surface it as an expected manual step.
  if ! ssl_mode_full; then
    fail sslmode
  fi
}

# Issuer of the cert Caddy presents for one vhost, polled while ACME finishes.
cert_issuer() {
  local h="$1" i=0 iss=""
  while [ $i -lt 45 ]; do
    iss=$(echo | timeout 10 openssl s_client -connect 127.0.0.1:443 -servername "$h.$DOMAIN" 2>/dev/null \
      | openssl x509 -noout -issuer 2>/dev/null | cut -d'=' -f2-)
    case "$iss" in *"Let's Encrypt"*) break;; esac
    i=$((i+2)); sleep 2
  done
  echo "$iss"
}

issue_certs() {
  local hosts="" h iss pending=()
  hosts="www"
  [ "${MOD_CLOUD:-true}" = "true" ]   && hosts="$hosts cloud talk"
  [ "${MOD_VAULT:-true}" = "true" ]   && hosts="$hosts vault"
  [ "${MOD_MONITOR:-true}" = "true" ] && hosts="$hosts kuma"
  [ "${MOD_MAIL:-true}" = "true" ]    && hosts="$hosts mail"
  for h in $hosts; do
    curl -sk --resolve "$h.$DOMAIN:443:127.0.0.1" -o /dev/null "https://$h.$DOMAIN/" >>"$LOG" 2>&1 || true
    sleep 3
  done
  # The trigger requests above only wake Caddy up — the first DNS-01 issuance
  # is not instant, so cert_issuer polls before declaring failure.
  for h in $hosts; do
    case "$(cert_issuer "$h")" in *"Let's Encrypt"*) ;; *) pending+=("$h");; esac
  done
  # Caddy's ACME retry backoff can leave a single order stuck (observed on
  # kuma.$DOMAIN: every other vhost issued, kuma's lock kept retrying) — one
  # restart re-attempts the pending identifiers.
  if [ ${#pending[@]} -gt 0 ]; then
    log "  ${#pending[@]} cert(s) pending (${pending[*]}) — restarting Caddy to re-attempt"
    # The container is named `caddy` (compose container_name), not $DOMAIN —
    # restarting "$DOMAIN" always failed with "No such container" and the
    # re-attempt never happened (2026-09-25).
    docker restart caddy >>"$LOG" 2>&1 || true
    sleep 5
  fi
  for h in $hosts; do
    iss=$(cert_issuer "$h")
    case "$iss" in
      *"Let's Encrypt"*) ;;
      *) fail "cert_$h" "issuer was: $iss";;
    esac
  done
}

# Old-project references must not survive in anything the installer deploys
# (compose files, host config, Makefile, recipes). docs/ and scripts/ are out
# of scope by design: docs record the rename as history, and the scripts
# (this installer, the rewrite/import tooling) name the old project by nature
# — counting them made the check unsatisfiable on the repo's own tree.
sweep_hits() {
  grep -rlI '$GITHUB_USER' "$REPO" \
    --exclude-dir=.git --exclude-dir=docs --exclude-dir=archives --exclude-dir=scripts 2>/dev/null || true
}

sweep() {
  [ -z "$(sweep_hits)" ] || fail sweep
}

phase_stack() {
  log "Phase 2 (stack): repo, host config, containers, DNS, certs"
  # Fail fast: the Cloudflare zone must already exist (the script cannot
  # create one — that needs nameservers pointing at Cloudflare).
  if [ -z "$(curl -s -H "Authorization: Bearer $CF_API_TOKEN" \
        "https://api.cloudflare.com/client/v4/zones?name=$DOMAIN" | jq -r '.result[0].id // empty')" ]; then
    fail zone "create the zone in the CF dashboard (point your nameservers there), then re-run"
    exit 1
  fi
  ensure_repo
  prep_dirs
  seed_stack
  docker_net
  caddy_data
  cf_dns
  host_services
  containers_up
  # per-module setup, in dependency order (default: everything ON)
  if [ "${MOD_CLOUD:-true}" = "true" ]; then
    nextcloud_setup
  fi
  [ "${MOD_VAULT:-true}" = "true" ] && vaultwarden_setup
  [ "${MOD_MAIL:-true}" = "true" ] && dkim_setup
  issue_certs
  [ "${MOD_MONITOR:-true}" = "true" ] && kuma_seed
  sweep
}

