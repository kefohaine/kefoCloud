resolve_errors() {
  local remaining=("${ERR_TAGS[@]}")
  while [ ${#remaining[@]} -gt 0 ]; do
    local exp=() unexp=()
    for tag in "${remaining[@]}"; do
      if is_expected "$tag"; then exp+=("$tag"); else unexp+=("$tag"); fi
    done
    if [ ${#exp[@]} -gt 0 ]; then
      _section "Manual steps (expected)" "$C_ORANGE"
      for i in "${!exp[@]}"; do
        _note "$(printf '  %s%d.%s %s%s%s' "$C_ORANGE" "$((i+1))" "$C_RST" "$C_ORANGE" "${exp[$i]}" "$C_RST")"
        _note "$(printf '     %sproblem:%s %s%s' "$C_GREY" "$C_RST" "$(problem "${exp[$i]}")" "${ERR_DETAIL[${exp[$i]}]:+ (${ERR_DETAIL[${exp[$i]}]})}")"
        _note "$(printf '     %shint:%s %s' "$C_GREY" "$C_RST" "$(hint "${exp[$i]}")")"
      done
    fi
    if [ ${#unexp[@]} -gt 0 ]; then
      _section "Unexpected errors (${#unexp[@]})" "$C_RED"
      for i in "${!unexp[@]}"; do
        _note "$(printf '  %s%d.%s %s%s%s' "$C_RED" "$((i+1))" "$C_RST" "$C_RED" "${unexp[$i]}" "$C_RST")"
        _note "$(printf '     %sproblem:%s %s%s' "$C_GREY" "$C_RST" "$(problem "${unexp[$i]}")" "${ERR_DETAIL[${unexp[$i]}]:+ (${ERR_DETAIL[${unexp[$i]}]})}")"
        _note "$(printf '     %shint:%s %s' "$C_GREY" "$C_RST" "$(hint "${unexp[$i]}")")"
      done
    fi
    if [ ! -t 0 ]; then
      # No terminal to answer on (piped/cron/CI run): a re-check prompt would
      # park the run forever with no way to proceed. Record the pending state
      # and stop LOUD instead — the errors above are already printed.
      _note "No terminal to re-check on — recording finished=false and stopping."
      FINISHED=false
      write_state
      exit 1
    fi
    printf '%s[INFO]%s Fix / complete the items above, then press Enter to re-check (Ctrl-C aborts): ' "$C_GREY" "$C_RST"
    read -r input \
      || { _note "No terminal input — aborting."; exit 1; }
    local still=()
    for tag in "${remaining[@]}"; do
      # A recorded setup failure is not a boolean to probe — re-RUN its setup
      # step first (the steps are idempotent), then inspect the state it leaves.
      # Without this a tag whose recheck arm inspects occ config (nextcloud_setup)
      # or a mailbox (vaultwarden_setup) can never heal: nextcloud_setup's own
      # wiring only ran during the failed pass, and the containers it was running
      # against are recreated by then (2026-10-15).
      case "$tag" in
        nextcloud_setup) mail_wait_ready 2>/dev/null || true; nextcloud_setup;;
        vaultwarden_setup) vaultwarden_setup;;
        dkim_setup) mail_wait_ready 2>/dev/null || true; dkim_setup;;
      esac
      if recheck "$tag"; then
        _note "$(printf '   %s✓ solved%s: %s — %s' "$C_GREEN" "$C_RST" "$tag" "$(problem "$tag")")"
      else
        still+=("$tag")
      fi
    done
    remaining=("${still[@]}")
  done
  ERR_TAGS=()
  write_state
  finalize_hardening
  finalize_install
}

# The install checkpoint gate — the LAST thing a green run does, in this order:
#   1. the stack is up (assets installed) — already true when this runs.
#   2. GitHub push (opt-in + an authorized key): a --no-verify push to a
#      TEMPORARY remote. It runs BEFORE the checkpoint on purpose: a rejected
#      push (not a collaborator, diverged history) means the run is NOT done, so
#      no `finished=true` is ever recorded for it. github_push returns 0
#      immediately when NOT opted in.
#   3. record the install: enabled_modules + finished=true, via write_state.
#   4. ONE `make smoke` — the "is everything actually done?" source. The gate it
#      enforces (install.state finished=true) is why the checkpoint is written
#      FIRST; its EXIT CODE is the verdict (core + enabled modules decide it, a
#      not-installed module's checks are informational only).
#   5. finished=false + stop, no success block, when smoke fails. Fail LOUD.
# Nothing but this script ever writes install.state: `make smoke` only reports,
# and install.sh records the verdict of the single call it makes.
# CHECKPOINT_OPEN guards the window between step 3 and the last decision: if the
# run is interrupted there, the EXIT trap reverts finished to false.
run_smoke() {
  detail "  running the live edge smoke test (make smoke) — the last check"
  # ONE call, ONE source of truth: `make smoke`'s exit code. smoke itself never
  # writes install.state — this script reads the code and records the verdict
  # (that is what keeps install.sh the sole writer, and what lets an operator's
  # own `make smoke`, and the pre-push hook, only report).
  if make -C "$REPO" smoke >>"$LOG" 2>&1; then
    detail "  smoke passed — the edge and every enabled module answer"
    return 0
  fi
  detail "  SMOKE FAILED — the edge is not fully serving every enabled module"
  msg "  SMOKE FAILED — re-run 'make smoke' and fix what it reports (full output: $LOG)"
  return 1
}

finalize_install() {
  # 1-2: the push happens BEFORE the checkpoint. If GitHub was opted in the push
  # is MANDATORY — any failure to push (no key, rejected (non-collaborator),
  # diverged history) means the install is not finished, so no finished=true is
  # recorded and the success block is never reached.
  local ok=1
  github_push || ok=0
  if [ "$ok" != 1 ]; then
    FINISHED=false
    write_state
    echo ""
    msg " NOT FINISHED — the GitHub push failed (see above / $LOG)."
    echo " Fix it, then re-run the installer to finish."
    return 0
  fi
  # 3: the checkpoint opens; smoke's exit code below decides whether it stands.
  FINISHED=true
  CHECKPOINT_OPEN=1
  write_state
  # 4-5: smoke's exit code is the verdict. Pass → the checkpoint we just wrote
  # stands (finished=true). Fail → this script writes finished=false and stops.
  # "Smoke Pass" is the last checklist row, marked here because smoke only runs
  # after the push and the finished checkpoint.
  task_start
  if ! run_smoke; then
    TASK_ERR=1
    FINISHED=false
    write_state
    CHECKPOINT_OPEN=
    task_end
    echo ""
    msg " NOT FINISHED — install.state is recorded pending (finished=false)."
    echo " Fix the failure above, then re-run the installer to finish."
    return 0
  fi
  task_end
  CHECKPOINT_OPEN=
  success_block
  ask_optimize
}

# ── Optional follow-up — only ever reached after a FULLY green run ────────
# optimize.sh is a separate tool (the machine performance pass), so it is offered,
# never assumed. It is idempotent — re-running it is a no-op — which is why a
# re-run of install.sh may offer it again.
ask_optimize() {
  local answer rc
  [ -f "$REPO/scripts/ops/optimize.sh" ] || return 0
  if ! ask_boolean "Also run the machine performance pass (kernel, swap, disk tuning) now?" answer; then
    return 0
  fi
  if [ "$answer" != "true" ]; then
    log "  optimize.sh skipped — run it later: bash $REPO/scripts/ops/optimize.sh"; return 0
  fi
  detail "  running scripts/ops/optimize.sh --yes (its output goes to $LOG)"
  bash "$REPO/scripts/ops/optimize.sh" --yes 2>&1 | tee -a "$LOG"
  rc=${PIPESTATUS[0]}
  if [ "$rc" = 0 ]; then
    detail "  optimize.sh done"
  else
    detail "  optimize.sh exited $rc — it is optional and can be re-run any time: bash $REPO/scripts/ops/optimize.sh"
  fi
}

finalize_hardening() {
  # Runs once every error is resolved: if a key exists now, harden sshd
  # (phase 1 skipped it when no key was present at install time). Same
  # change-detection as task_ssh — a re-run that writes identical config does
  # not restart sshd, so an operator's session is never dropped for nothing.
  if [ -s /root/.ssh/authorized_keys ]; then
    local before after
    before=$(cat /etc/ssh/sshd_config.d/50-cloud-init.conf 2>/dev/null | sha256sum)
    printf 'PasswordAuthentication no\nPermitRootLogin prohibit-password\nAllowUsers root\n' \
      > /etc/ssh/sshd_config.d/50-cloud-init.conf
    chmod 600 /etc/ssh/sshd_config.d/50-cloud-init.conf
    after=$(cat /etc/ssh/sshd_config.d/50-cloud-init.conf 2>/dev/null | sha256sum)
    [ "$before" = "$after" ] || systemctl restart sshd >/dev/null 2>&1 || true
  fi
  # Close the temporary installer-session SSH rule (tailnet access stays).
  local ip="${INSTALLER_SSH_IP:-}"
  if [ -n "$ip" ] && [ "$ip" != "$(tailscale ip -4 2>/dev/null | head -1)" ]; then
    ufw --force delete allow from "$ip" to any port 22 proto tcp >/dev/null 2>&1 || true
    ufw delete allow from "$ip" to any port 22 proto tcp >/dev/null 2>&1 || true
    detail "  removed the temporary installer SSH allow for $ip (root@$NODE_NAME over the tailnet remains the entry point)"
  fi
  # Also remove any remaining stale SSH rules from prior installs.
  while IFS= read -r _ip; do
    [ "$_ip" = "100.64.0.0/10" ] && continue
    ufw --force delete allow from "$_ip" to any port 22 proto tcp >/dev/null 2>&1 || true
  done < <(ufw status numbered 2>/dev/null | grep '22/tcp' | awk '{print $NF}')
}

