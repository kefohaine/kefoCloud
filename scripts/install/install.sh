load_state() {
  [ -f "$STATE" ] && . "$STATE"
  local uniq=() t
  for t in "${ERR_TAGS[@]:-}"; do
    [[ " ${uniq[*]:-} " == *" $t "* ]] || uniq+=("$t")
  done
  ERR_TAGS=("${uniq[@]}")
}

save_state() {
  umask 077
  install -d -m 0700 "$(dirname "$STATE")"
  local tmp="$STATE.tmp.$$"
  cat > "$tmp" <<EOF
DOMAIN='$DOMAIN'
CF_API_TOKEN='$CF_API_TOKEN'
TS_AUTHKEY='$TS_AUTHKEY'
TS_IP='${TS_IP:-}'
MOD_CLOUD='${MOD_CLOUD:-true}'
MOD_VAULT='${MOD_VAULT:-true}'
MOD_MAIL='${MOD_MAIL:-true}'
MOD_MONITOR='${MOD_MONITOR:-true}'
ERR_TAGS=($(printf '%q ' "${ERR_TAGS[@]}"))
EOF
  chmod 600 "$tmp"
  mv -f "$tmp" "$STATE" 2>/dev/null || sudo mv -f "$tmp" "$STATE" || rm -f "$tmp"
  chown root:root "$STATE" 2>/dev/null || true
}

# $LOG and $STATE live outside the repo and must exist before ANYTHING redirects
# into them (a `>>"$LOG"` whose directory is missing fails the redirection, the
# command behind it is never run, and `|| fail ...` then reports the step as
# broken) — and before the first `log()`, or tee swallows that line. Idempotent;
# main() calls it first thing.
ensure_runtime_dirs() {
  install -d -m 0755 "$LOG_DIR"
  install -d -m 0700 "$STATE_DIR"
}

# Module prompts are ALWAYS asked — there is no answer-sheet defaults file any
# more. A pre-filled default is exactly how a stale value (e.g. DOMAIN left over
# from a previous run) silently skipped a prompt the operator needed to see.
# Every boolean prompt takes an EXPLICIT true or false: no Enter-accepts-default,
# and never a default of true — a pre-selected answer is how a stale choice
# survives a re-run. Anything else re-asks.
ask_boolean() {   # ask_boolean <question> <variable>
  local q="$1" var="$2" answer
  while :; do
    read -rp "$q (true/false): " answer || return 1
    case "${answer,,}" in
      true)  printf -v "$var" '%s' true;  return 0 ;;
      false) printf -v "$var" '%s' false; return 0 ;;
      *)     echo "   type true or false." ;;
    esac
  done
}

ask_modules() {
  local k var
  for k in cloud vault mail monitor; do
    var="MOD_${k^^}"
    [ -n "${!var:-}" ] && continue        # already answered (resume)
    ask_boolean "Set up the $k module?" "$var" || exit 1
  done
}

# ── SSH access: STRICT and required ──────────────────────────────────────
# The box ends up root-key-only with password auth off, so a usable pubkey from
# a device the operator actually holds is REQUIRED — the installer asks for it
# here instead of leaving it as a follow-up `ssh_keys` step. Only the PUBLIC
# half is pasted; the private half never leaves that device. Nothing is ever
# minted server-side (that is the difference to the opt-in GitHub key below).
ask_ssh_key() {
  local line info
  mkdir -p /root/.ssh && chmod 700 /root/.ssh
  if [ -s /root/.ssh/authorized_keys ] && grep -q . /root/.ssh/authorized_keys; then
    log "  SSH: $(grep -c . /root/.ssh/authorized_keys) key(s) already authorized — paste skipped"
    return 0
  fi
  printf '\n SSH is key-only (root, no password). On the device you will connect FROM run\n'
  printf '   cat ~/.ssh/id_ed25519.pub\n'
  printf ' and paste that one line here (no ssh-copy-id needs to run yet). Only the\n'
  printf ' PUBLIC half goes to the server; the private half never leaves your device.\n'
  printf ' Use a key you can actually use — hardening is key-only, so a wrong or lost\n'
  printf ' key is a lockout.\n\n'
  while :; do
    read -rp "Public SSH key of your device: " line \
      || { echo "A public key is required — re-run the installer from a terminal."; exit 1; }
    line="$(printf '%s' "$line" | tr -d '\r' | sed 's/^[[:space:]]*//; s/[[:space:]]*$//')"
    case "$line" in
      "") continue ;;
      *"PRIVATE KEY"*) echo "   that is the PRIVATE key — never paste it; paste the .pub line."; continue ;;
    esac
    info="$(printf '%s\n' "$line" | ssh-keygen -lf - 2>/dev/null)"
    [ -n "$info" ] || { echo "   not a valid public key — paste the whole .pub line (ssh-ed25519 AAAA… you@device)."; continue; }
    grep -qxF "$line" /root/.ssh/authorized_keys 2>/dev/null \
      || printf '%s\n' "$line" >> /root/.ssh/authorized_keys
    chmod 600 /root/.ssh/authorized_keys
    log "  SSH key accepted: $info"
    return 0
  done
}

ask_inputs() {
  if [ -z "${DOMAIN:-}" ]; then
    read -rp "Domain (e.g. example.com): " DOMAIN
  fi
  DOMAIN="${DOMAIN,,}"
  [[ "$DOMAIN" =~ ^[a-zA-Z0-9.-]+\.[a-zA-Z]{2,}$ ]] || { echo "Invalid domain: $DOMAIN"; exit 1; }
  if [ -z "${CF_API_TOKEN:-}" ]; then
    read -rsp "Cloudflare API token (Zone > DNS > Edit): " CF_API_TOKEN; echo
  fi
  [ -n "$CF_API_TOKEN" ] || { echo "Token required."; exit 1; }
  if [ -z "${TS_AUTHKEY:-}" ]; then
    read -rsp "Tailscale auth key (tskey-...): " TS_AUTHKEY; echo
  fi
  [ -n "$TS_AUTHKEY" ] || { echo "Auth key required."; exit 1; }
  ask_modules
  # STRICT: key-only SSH means a usable pubkey is required, asked BEFORE the
  # GitHub question below (that one is opt-in).
  ask_ssh_key
  # LAST prompt, opt-in, explicit true/false: mint a GitHub key for pushing to
  # the operator's OWN repos, print it, wait until it is authorized, push.
  [ -n "${GH_REMOTE:-}" ] || ask_boolean "Configure remote access to your own GitHub account's repositories?" GH_REMOTE || exit 1
  echo "Installing for $DOMAIN — ~10-15 min. Full log: $LOG"
}

# Module detection, cross-checked. Written at the END of a successful install
# and refreshed on every re-run. Three artefacts, all under $DATA (gitignored):
#   installed-modules.conf           declared modules (the install-time choice)
#   installed-modules.detected.conf  modules confirmed by independent probes
#   installed-modules.report.txt     per-module, per-method evidence matrix
# Probes, deliberately independent of the declared choice: (1) the container
# is running, (2) its compose file exists in the repo, (3) its data dir/db
# exists on disk, (4) its Caddy vhost exists. A module is "confirmed" when at
# least one probe fires; a declared/confirmed mismatch is logged as a warning.
# Consumed by scripts/stack/smoke-vhosts.sh + scripts/info/fetch.sh.
write_modules_conf() {
  local conf="$DATA/installed-modules.conf"
  local det="$DATA/installed-modules.detected.conf"
  local rep="$DATA/installed-modules.report.txt"
  local m ct cf dd vh ev

  : > "$conf"; : > "$det"
  { echo "module detection report — $(date -Is)"
    echo "declared = install-time choice (MOD_*); probes are independent of it."
    echo; } > "$rep"

  for m in cloud vault mail monitor; do
    [ "${MOD_${m^^}:-true}" = "true" ] && echo "$m" >> "$conf"
  done

  for m in cloud vault mail monitor; do
    ct=0; cf=0; dd=0; vh=0
    case "$m" in
      cloud)   ct=$(docker ps --format '{{.Names}}' 2>/dev/null | grep -cx nextcloud)
               [ -f "$REPO/modules/nextcloud/docker-compose.yml" ] && cf=1
               [ -e "$DATA/cloud/users" ] && dd=1
               [ -f "$RENDER_DIR/caddy/vhosts/cloud.caddy" ] && vh=1 ;;
      vault)   ct=$(docker ps --format '{{.Names}}' 2>/dev/null | grep -cx vaultwarden)
               [ -f "$REPO/modules/vaultwarden/docker-compose.yml" ] && cf=1
               [ -e "$DATA/vault/data" ] && dd=1
               [ -f "$RENDER_DIR/caddy/vhosts/vault.caddy" ] && vh=1 ;;
      mail)    ct=$(docker ps --format '{{.Names}}' 2>/dev/null | grep -cxE 'mailserver|roundcube')
               [ -f "$REPO/modules/mailserver/docker-compose.yml" ] && cf=1
               [ -e "$DATA/mailserver/data" ] && dd=1
               [ -f "$RENDER_DIR/caddy/vhosts/mail.caddy" ] && vh=1 ;;
      monitor) ct=$(docker ps --format '{{.Names}}' 2>/dev/null | grep -cx uptimekuma)
               [ -f "$REPO/modules/uptimekuma/docker-compose.yml" ] && cf=1
               [ -e "$DATA/kuma/data" ] && dd=1
               [ -f "$RENDER_DIR/caddy/vhosts/kuma.caddy" ] && vh=1 ;;
    esac
    ev=$((ct+cf+dd+vh))
    [ "$ev" -gt 0 ] && echo "$m" >> "$det"
    printf '%-8s declared=%s running=%s compose=%s data=%s vhost=%s -> %s\n' \
      "$m" "$([ "${MOD_${m^^}:-true}" = true ] && echo 1 || echo 0)" \
      "$ct" "$cf" "$dd" "$vh" "$([ "$ev" -gt 0 ] && echo PRESENT || echo absent)" >> "$rep"
  done

  log "  wrote $conf ($(paste -sd' ' "$conf"))"
  log "  detected: $(paste -sd' ' "$det" || echo none) — evidence: $rep"
  if ! diff -q <(sort "$conf") <(sort "$det") >/dev/null 2>&1; then
    log "  WARNING: declared modules != detected modules — see $rep"
  fi
}

# ───────────────── GitHub remote access (opt-in, last prompt) ─────────────

# The ONE keypair this installer mints: it has to exist on the box to push to
# the operator's repos. (The operator's own login key is never minted — it is
# pasted at the ask_ssh_key prompt.) The operator authorizes the printed PUBLIC
# key once.
GH_KEY=/root/.ssh/github_key

github_keygen() {
  [ -s "$GH_KEY" ] && return 0                      # never overwrite an existing key
  ssh-keygen -t ed25519 -N "" -C "$(id -un)@$(hostname -s) github_key" -f "$GH_KEY" >/dev/null 2>&1 || return 1
  chmod 600 "$GH_KEY"; chmod 644 "$GH_KEY.pub"
  # ssh does not offer this key by default: name it in the client config.
  grep -qs "IdentityFile $GH_KEY" /root/.ssh/config 2>/dev/null && return 0
  printf 'Host github.com\n  IdentityFile %s\n  IdentitiesOnly yes\n' "$GH_KEY" >> /root/.ssh/config
  chmod 600 /root/.ssh/config
}

# Pin github.com's host keys, but only ones whose fingerprint api.github.com
# publishes — a bare ssh-keyscan trusts whoever answered first.
github_known_hosts() {
  local scan fps published f n=0
  grep -qs 'github\.com' /root/.ssh/known_hosts 2>/dev/null && return 0
  scan="$(ssh-keyscan -t rsa,ecdsa,ed25519 github.com 2>/dev/null)" || return 0
  [ -n "$scan" ] || return 0
  fps="$(printf '%s\n' "$scan" | ssh-keygen -lf - 2>/dev/null | awk '{print $2}')"
  published="$(curl -fsS --max-time 10 https://api.github.com/meta 2>/dev/null \
    | python3 -c 'import json,sys; print("\n".join(json.load(sys.stdin)["ssh_key_fingerprints"].values()))' 2>/dev/null)"
  for f in $fps; do
    n=$((n+1))
    printf '%s\n' "$published" | grep -qxF "$f" || return 0   # unverified — leave it to ssh
  done
  [ "$n" -gt 0 ] && printf '%s\n' "$scan" >> /root/.ssh/known_hosts && chmod 600 /root/.ssh/known_hosts
}

# GitHub answers a successful key test with exit 1 and a "successfully
# authenticated" line, so the MESSAGE is the test, not the exit code — and the
# output has to be captured first: under `set -o pipefail` a `ssh … | grep -q`
# reports ssh's 1 even when grep matched.
github_auth_ok() {
  local out
  [ -s "$GH_KEY" ] || return 1
  out="$(ssh -o BatchMode=yes -o StrictHostKeyChecking=accept-new -T git@github.com 2>&1)" || true
  printf '%s' "$out" | grep -q "successfully authenticated"
}

github_push() {
  git -C "$REPO" remote set-url origin "git@github.com:$GITHUB_USER/$REPO_NAME.git" 2>/dev/null || true
  # SKIP_SMOKE: the pre-push hook's live vhost test cannot pass this early — the
  # stack is not up yet, and what is pushed here is the repo's content.
  SKIP_SMOKE=1 git -C "$REPO" push >>"$LOG" 2>&1 || return 1
}

github_access() {
  [ "${GH_REMOTE:-false}" = "true" ] || { log "  GitHub remote access: not requested — skipped"; return 0; }
  github_keygen || { fail github_key; return; }
  github_known_hosts
  if ! github_auth_ok; then
    printf '\n ── GitHub key — authorize it once, then the installer continues ───────\n'
    printf '   GitHub → Settings → SSH and GPG keys → New SSH key → paste this line:\n\n'
    printf '   %s\n\n' "$(cat "$GH_KEY.pub")"
    printf '   (Settings is under the avatar menu, top right; "New SSH key" is the\n'
    printf '    green button in the SSH keys box — name it after this host.)\n'
    printf ' ───────────────────────────────────────────────────────────────────────\n\n'
    # Strict: the operator asked for this feature, so there is no skip — the
    # loop only ends when GitHub accepts the key (Ctrl-C aborts the installer).
    until github_auth_ok; do
      read -rp "Add the key at GitHub, then press Enter to test again (Ctrl-C aborts): " _ \
        || { fail github_auth "no terminal to wait on — authorize $GH_KEY.pub by hand"; return; }
      echo "   not authorized yet — the whole line above goes into your GitHub ACCOUNT."
    done
  fi
  log "  GitHub key authorized (ssh -T git@github.com)"
  if [ -z "${GITHUB_USER:-}" ] || [ "$GITHUB_USER" = "exampleuser" ]; then
    fail github_auth "cannot tell which account to push to — no origin remote and no GITHUB_USER in $DATA/instance.conf"
    return
  fi
  github_push || fail github_auth "push failed — see $LOG"
}

# ───────────────────────────── Phase 1 (root) ─────────────────────────────

phase_host() {
  log "Phase 1 (host): packages, ssh, docker, tailscale, firewall"
  # Log may contain host/secret-adjacent output — root-readable only, never 666.
  # One-time relocation off the pre-$GITHUB_USER paths (never drop the old log).
  if [ ! -f "$LOG" ]; then
    for old in /var/log/$NODE_NAME-install.log /var/log/homelab-install.log; do
      [ -f "$old" ] && { mv -f "$old" "$LOG"; break; }
    done
  fi
  if [ ! -f "$STATE" ] && [ -f /var/lib/$NODE_NAME/setup.state ]; then
    mv -f /var/lib/$NODE_NAME/setup.state "$STATE"
  fi
  touch "$LOG" && chmod 640 "$LOG"

  # Canonical machine name: the repo, the tailnet node and root@$NODE_NAME must
  # all be 'kefoserver'. Set the static hostname so they agree even on a provider
  # image whose hostname is a throwaway (vps-xxxxxxxx).
  if [ "$(hostname -s 2>/dev/null)" != "$NODE_NAME" ]; then
    hostnamectl set-hostname "$NODE_NAME" >>"$LOG" 2>&1 || true
    log "  hostname set to $NODE_NAME (tailnet node will be $NODE_NAME)"
  fi

  DEBIAN_FRONTEND=noninteractive apt-get update -qq >>"$LOG" 2>&1
  # bzip2 is REQUIRED: goose's official download_cli.sh ships a .tar.bz2 — without
  # bzip2 the extraction fails and goose lands in the error list as a phantom
  # "unexpected error" whose real cause is a missing extractor.
  # dnsutils = dig: the dkim_setup re-check and its hint query the zone's
  # nameserver directly ("dig +short TXT mail._domainkey.$DOMAIN @<zone NS>"),
  # so without it that re-check could never pass and the installer looped on a
  # dkim tag whose only fault was a missing tool (2026-09-25).
  DEBIAN_FRONTEND=noninteractive apt-get install -y -qq \
    git curl make sudo dnsmasq ufw jq apache2-utils fail2ban sqlite3 python3-yaml tmux bzip2 dnsutils >>"$LOG" 2>&1 || fail apt
  # Docker: Debian packages first (bookworm ships docker-compose-plugin).
  # trixie does not, so fall back to Docker's official repo (docker-ce).
  if ! DEBIAN_FRONTEND=noninteractive apt-get install -y -qq docker.io docker-compose-plugin >>"$LOG" 2>&1; then
    log "  docker-compose-plugin not in distro — installing docker-ce from Docker's repo"
    DEBIAN_FRONTEND=noninteractive apt-get install -y -qq ca-certificates curl gnupg >>"$LOG" 2>&1
    install -m 0755 -d /etc/apt/keyrings
    curl -fsSL https://download.docker.com/linux/debian/gpg | gpg --yes --dearmor -o /etc/apt/keyrings/docker.gpg 2>>"$LOG"
    chmod a+r /etc/apt/keyrings/docker.gpg
    echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.gpg] https://download.docker.com/linux/debian $(. /etc/os-release && echo "$VERSION_CODENAME") stable" \
      > /etc/apt/sources.list.d/docker.list
    DEBIAN_FRONTEND=noninteractive apt-get update -qq >>"$LOG" 2>&1
    DEBIAN_FRONTEND=noninteractive apt-get install -y -qq docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin >>"$LOG" 2>&1 || fail apt
  fi
  command -v docker >/dev/null 2>&1 || fail apt

  # Single operator account: root. The provider image may ship a login-capable
  # account (e.g. the cloud-init 'debian' user) — remove every non-root account
  # with a real UID so root@$NODE_NAME is genuinely the only way in.
  local u uid home
  while IFS=: read -r u _ uid _ _ home _; do
    [ "$u" = root ] && continue
    [ "$uid" -ge 1000 ] 2>/dev/null || continue
    [ "$uid" -lt 65534 ] || continue
    log "  removing non-root login account '$u' ($home)"
    pkill -u "$u" 2>/dev/null || true
    sleep 1
    userdel -r "$u" >>"$LOG" 2>&1 || userdel "$u" >>"$LOG" 2>&1 || true
  done < <(getent passwd)

  # SSH: root key-only. The operator's pubkey is collected by ask_ssh_key BEFORE
  # this phase (strict), so a missing key here means the step failed — the
  # `ssh_keys` guard stays as the safety net, and hardening (password auth off,
  # root key-only) is applied ONLY once a usable key exists, so the box is never
  # locked out. The installer never mints a server-side login keypair.
  mkdir -p /root/.ssh
  chmod 700 /root/.ssh
  if [ -s /root/.ssh/authorized_keys ]; then
    chmod 600 /root/.ssh/authorized_keys
    printf 'PasswordAuthentication no\nPermitRootLogin prohibit-password\nAllowUsers root\n' \
      > /etc/ssh/sshd_config.d/50-cloud-init.conf
    chmod 600 /etc/ssh/sshd_config.d/50-cloud-init.conf
    systemctl restart sshd
    log "  sshd hardened: key-only root login (AllowUsers root)"
  else
    fail ssh_keys
    log "no SSH key in /root/.ssh/authorized_keys (ask_ssh_key should have installed one) — add a pubkey, then re-check; sshd stays password-capable until then"
  fi

  systemctl enable --now docker >>"$LOG" 2>&1 || log "docker enable/start failed (re-checks will catch it)"
  mkdir -p /etc/docker
  # Write the daemon config only if it differs — never clobber a working one.
  cat > /etc/docker/daemon.json.new <<'EOF'
{
    "log-driver": "json-file",
    "log-opts": {"max-size": "10m", "max-file": "3"},
    "storage-driver": "overlay2",
    "default-runtime": "runc",
    "live-restore": true
}
EOF
  if ! diff -q /etc/docker/daemon.json /etc/docker/daemon.json.new >/dev/null 2>&1; then
    mv /etc/docker/daemon.json.new /etc/docker/daemon.json
    systemctl restart docker >>"$LOG" 2>&1 || log "docker restart failed (re-checks will catch it)"
  else
    rm -f /etc/docker/daemon.json.new
  fi
  if ! systemctl is-active --quiet docker; then
    systemctl start docker >>"$LOG" 2>&1 || log "docker start failed (re-checks will catch it)"
  fi

  if ! command -v goose >/dev/null 2>&1 && [ ! -x /usr/local/bin/goose ]; then
    # Official installer (release archive, .tar.bz2 — hence the bzip2 apt dep
    # above). Its output goes to the log, not /dev/null, so a failure is
    # diagnosable instead of surfacing as a bare "goose binary not installed".
    curl -fsSL https://github.com/aaif-goose/goose/releases/download/stable/download_cli.sh \
      | CONFIGURE=false GOOSE_BIN_DIR=/usr/local/bin bash >>"$LOG" 2>&1 || true
  fi
  if command -v goose >/dev/null 2>&1; then
    install -m 0755 "$(command -v goose)" /usr/local/bin/goose || true
  elif [ -x "$HOME/.local/bin/goose" ]; then
    install -m 0755 "$HOME/.local/bin/goose" /usr/local/bin/goose || true
  fi
  command -v goose >/dev/null 2>&1 || [ -x /usr/local/bin/goose ] || fail goose

  if ! command -v tailscale >/dev/null 2>&1; then
    curl -fsSL https://tailscale.com/install.sh | sh || fail tailscale
  fi
  # Encrypt the tailscaled state file at rest (the console's tsStateEncrypted).
  # On Linux the flag NEEDS a TPM (/dev/tpmrm0): on a box without one, forcing
  # `--encrypt-state` makes tailscaled fail to start and takes the node offline,
  # so enable it only when the device exists — and start tailscaled fresh with
  # it before joining, so the state is encrypted from the first write.
  if [ -e /dev/tpmrm0 ] && [ -f /etc/default/tailscaled ]; then
    if ! grep -q -- '--encrypt-state' /etc/default/tailscaled; then
      sed -i -E 's|^FLAGS=.*|FLAGS="--encrypt-state"|' /etc/default/tailscaled
      systemctl restart tailscaled >>"$LOG" 2>&1 || log "tailscaled restart failed after enabling --encrypt-state"
      log "  tailscale state encryption enabled (FLAGS=--encrypt-state, TPM present)"
    fi
  elif [ ! -e /dev/tpmrm0 ]; then
    log "  no TPM (/dev/tpmrm0): tailscale state encryption unsupported here — left off"
  fi
  if ! tailscale ip -4 >/dev/null 2>&1; then
    # --hostname makes the tailnet node '$NODE_NAME', so the sole entry point
    # is root@$NODE_NAME (MagicDNS) regardless of the local machine hostname.
    tailscale up --authkey="$TS_AUTHKEY" --hostname=$NODE_NAME >>"$LOG" 2>&1 || fail tailscale_up
  fi
  TS_IP=$(tailscale ip -4 2>/dev/null | head -1)
  [ -n "$TS_IP" ] && log "tailscale IP: $TS_IP" || fail ts_ip

  ufw allow from 100.64.0.0/10 to any port 22 proto tcp >/dev/null 2>&1
  # Keep the current SSH client reachable even before it joins the tailnet, so
  # enabling ufw never locks the operator out mid-install. This is a TEMPORARY
  # rule for the installer session only: the IP is remembered and the rule is
  # deleted once the run succeeds (finalize_hardening) — a permanent rule for a
  # consumer/dynamic IP would be a standing hole.
  INSTALLER_SSH_IP="${SSH_CLIENT:+$(echo "$SSH_CLIENT" | awk '{print $1}')}"
  if [ -n "$INSTALLER_SSH_IP" ]; then
    ufw allow from "$INSTALLER_SSH_IP" to any port 22 proto tcp >/dev/null 2>&1 || true
  fi
  ufw allow 80/tcp >/dev/null 2>&1
  ufw allow 443/tcp >/dev/null 2>&1
  # Self-hosted mail (Docker Mailserver): SMTP + submission + IMAPS. Inbound 25
  # can be provider-blocked on some VPSes — these are open so mail works the
  # moment the provider allows it.
  ufw allow 25/tcp >/dev/null 2>&1
  ufw allow 465/tcp >/dev/null 2>&1
  ufw allow 587/tcp >/dev/null 2>&1
  ufw allow 993/tcp >/dev/null 2>&1
  # Nextcloud Talk: TURN/STUN + relay range (talk.$DOMAIN must stay DNS-only).
  ufw allow 3478/udp >/dev/null 2>&1
  ufw allow 3478/tcp >/dev/null 2>&1
  ufw allow 5349/tcp >/dev/null 2>&1
  ufw allow 49160:49200/udp >/dev/null 2>&1
  ufw allow 49160:49200/tcp >/dev/null 2>&1
  echo y | ufw enable >/dev/null 2>&1 || true

  save_state
  chmod 600 "$STATE" 2>/dev/null || true
}

