  sudo chmod 0711 $ROOT/data/caddy_data
  sudo chown root:root $ROOT/data/caddy_data/CF_API_TOKEN
  sudo chmod 0644 $ROOT/data/caddy_data/CF_API_TOKEN
}

host_services() {
  [ -n "${TS_IP:-}" ] || fail ts_ip
  # The tracked 10-tailnet.conf keeps a PLACEHOLDER address — install-config
  # renders the live Tailscale IP in at deploy time, so the repo file is never
  # mutated and no instance-specific address is ever committed.
  make install-config >>"$LOG" 2>&1 || fail install_config
  # fail2ban: on trixie the default file backend finds no /var/log/auth.log and
  # the unit exits 255. Our jail.d/sshd.conf ships backend=systemd; restart and
  # verify so a silently-dead jail can never pass as hardened.
  systemctl restart fail2ban >>"$LOG" 2>&1 || true
  # `systemctl restart` returns while the unit is still activating, and
  # install-config restarts fail2ban again seconds later — so poll for the
  # server + the sshd jail instead of judging the unit on the first look
  # (2026-09-25: the tag fired ~0.3 s before the jail came up and then sat in
  # the summary as a phantom "not running" error on an active fail2ban).
  local i=0
  while [ $i -lt 30 ]; do
    systemctl is-active --quiet fail2ban && fail2ban-client status sshd >/dev/null 2>&1 && break
    sleep 1; i=$((i+1))
  done
  systemctl is-active --quiet fail2ban || fail fail2ban
  fail2ban-client status sshd >/dev/null 2>&1 || fail fail2ban
}

containers_up() {
  # The checklist's own [TASK] animation is the progress indicator, so the Caddy
  # build prints nothing here (its verbose output goes to $LOG). The dok-recreate
  # recipe already falls back to docker build + compose up when compose's buildx
  # is too old (Debian trixie).
  log "  recreate: caddy (image build)"
  make dok-recreate-caddy >>"$LOG" 2>&1 || fail caddy
  detail "  Caddy image built"
  # PostgreSQL first — the nextcloud entrypoint's fresh install needs the DB
  # reachable (POSTGRES_HOST from .env, set by talk-gen above). Caddy's
  # DNS-01 issuance runs at startup, so the mail/turn certs the talk stack
  # and mailserver need are on disk by the time they start. Modules respect
  # the install-time choice (default: everything ON).
  if mod_on cloud; then
    log "  recreate: nextcloud-db + nextcloud"
    # ONE compose invocation for BOTH files. They live in the same directory
    # (modules/nextcloud/), so compose treats them as one project — and running
    # `up --remove-orphans` on either file ALONE sees the other file's containers
    # as orphans and DELETES them. That is exactly what happened on 2026-10-15:
    # the app recreate removed the just-started postgresql, nextcloud could not
    # reach 172.22.0.15:5432, and `occ maintenance:install` died with
    # SQLSTATE[08006] "No route to host". Naming both -f files keeps every
    # service in the project, so nothing is ever an orphan.
    docker compose \
      -f "$REPO/modules/nextcloud/docker-compose.db.yml" \
      -f "$REPO/modules/nextcloud/docker-compose.yml" \
      up -d --force-recreate --remove-orphans >>"$LOG" 2>&1 \
      || { fail nextcloud_db; fail nextcloud; }
  fi
  mod_on vault && { log "  recreate: vaultwarden"; make dok-recreate-vaultwarden >>"$LOG" 2>&1 || fail vaultwarden; }
  mod_on monitor && { log "  recreate: uptimekuma";  make dok-recreate-uptimekuma  >>"$LOG" 2>&1 || fail kuma; }
  mod_on mail && { log "  recreate: mailserver";  make dok-recreate-mailserver  >>"$LOG" 2>&1 || fail mailserver; }
}

kuma_seed() {
  # Wait for the SCHEMA, not for the file. Kuma 2.5+ serves its "Setup
  # Database" wizard (port open, healthcheck green, kuma.db still 0 bytes) when
  # it can neither read db-config.json nor find a kuma.db — the compose file
  # now sets UPTIME_KUMA_DB_TYPE=sqlite so the main server starts and creates
  # the tables. Polling `test -f` was a trap: the poll timed out, sqlite3 then
  # CREATED an empty kuma.db and every seed statement failed with "no such
  # table" (2026-09-25).
  local i=0 ready=""
  while [ $i -lt 150 ]; do
    if docker exec uptimekuma sqlite3 /app/data/kuma.db \
         "SELECT 1 FROM sqlite_master WHERE type='table' AND name='user';" 2>/dev/null | grep -q 1; then
      ready=1; break
    fi
    sleep 2; i=$((i+2))
  done
  if [ -z "$ready" ]; then
    fail kuma_seed "kuma.db has no schema after 5 min (Kuma still in Setup Database)"
    return
  fi
  KUMA_PASS=$(openssl rand -base64 18 | tr -d '/+=' | head -c 20)
  local n
  n=$(docker exec uptimekuma sqlite3 /app/data/kuma.db "SELECT COUNT(*) FROM user WHERE username='admin';" 2>/dev/null | tr -d '\n')
  if [ "$n" = "0" ]; then
    local HASH
    HASH=$(htpasswd -bnBC 10 "" "$KUMA_PASS" 2>/dev/null | tr -d ':\n')
    if [ -n "$HASH" ]; then
      docker exec uptimekuma sqlite3 /app/data/kuma.db \
        "INSERT OR IGNORE INTO user (username,password,active,timezone) VALUES ('admin','$HASH',1,'UTC');" \
        >>"$LOG" 2>&1 || fail kuma_admin
    fi
  fi
  docker exec -i uptimekuma sqlite3 /app/data/kuma.db < modules/uptimekuma/seed-monitors.sql \
    >>"$LOG" 2>&1 || fail kuma_seed
}

# Idempotently create one mailserver mailbox, retrying until it takes.
# Password comes on stdin twice (value + confirmation), as `setup email add`
# expects. Two traps made the old one-shot call fail: docker-mailserver exits
# ~2 min after start when no account exists yet ("You need at least one mail
# account to start Dovecot (120s left...)") and compose restarts it, so the
# command can land in a dead/restarting window; and a single attempt gives no
# second chance once the installer has moved on (2026-09-25: both mailboxes
# uncreated, leaving the whole mail stack with no account).
# Wait until the mailserver's `setup` CLI is usable, not merely until the
# container is running. NOTE: probe `setup help`, never `setup email list` — with
# no accounts yet the list reads a store that does not exist, so the list returns
# non-zero and the wait can never satisfy itself (its first account comes from
# mailbox_add, which runs after it). mailbox_add stays the retry layer that
# absorbs a DMS restarting underneath a mid-add.
mail_wait_ready() {
  local i=0
  while [ $i -lt 300 ]; do
    # (a) the container is up and (b) its `setup` CLI runs. Probe with
    # `setup help`, NOT `setup email list`: with zero accounts the account store
    # that `list` reads does not exist yet, so `setup email list` fails and this
    # wait DEADLOCKS — the first account is only ever added by mailbox_add, which
    # runs AFTER this wait. On 2026-10-15 the mailserver boot-looped its
    # "no mail account to start Dovecot (120 s)" countdown for the full 5 min
    # while a healthy container answered `docker exec` the whole time, so dkim
    # and both sender mailboxes were reported failed for a container that was up.
    if docker exec mailserver true >/dev/null 2>&1 \
       && docker exec mailserver setup help >/dev/null 2>&1; then
      log "  mailserver setup CLI ready after ${i}s"
      return 0
    fi
    if ! docker exec mailserver true >/dev/null 2>&1; then
      log "  mailserver not running — recreating (attempt $((i/5+1)))"
      make dok-recreate-mailserver >>"$LOG" 2>&1 || true
    fi
    sleep 5; i=$((i+5))
  done
  fail mailserver "account API did not answer after 5 min"
  return 1
}

# Is the address in the mailserver's account list? The address itself decides —
# never the row's trailing quota formatting (DMS prints `(  /  ) [%]` for a
# quota-less mailbox and `( 0 / ~ ) [0%]` otherwise, and a probe account it
# normalizes can abort the whole listing with `_bytes_to_human_readable_size`).
mailbox_exists() {
  # Exact compare with grep -Fx, NOT a regex: an email address contains only
  # `[a-z0-9@.-]` by the time DMS has normalized it, so it needs no escaping —
  # and the escaping that was here (`${1//./\\\\.}`) produced a literal `\\.`
  # (backslash + any char) instead of `\.`, so the pattern matched nothing and
  # EVERY mailbox was reported "not created" while sitting in the account store
  # (2026-10-15 — this is the bug behind every vaultwarden_setup failure).
  docker exec mailserver setup email list 2>/dev/null \
    | sed -n 's/^[* ] *//p' | cut -d' ' -f1 \
    | grep -qFxi "$1"
}

# Add one mailbox FOR REAL — never a silent skip. `setup email add` writes the
# account, a hash and the Maildir, and it is idempotent enough that a retry
# after a restart re-adds what was lost. Its OUTPUT IS LOGGED (the old call
# redirected stderr to /dev/null, which is why four consecutive failures left
# nothing in install.log to diagnose — 2026-10-15). Verification goes through
# the mailserver's config file as well as its listing, so a container that
# answers the API while rejecting writes cannot be reported as success.
mailbox_add() {
  local addr="$1" pass="${2:-}" i=0 out
  # mail_wait_ready has already established that the account API answers, so
  # this is a bounded confirmation retry (90 s, in 5 s steps): the only thing
  # left to absorb is a container that restarted between the wait and this call.
  while [ $i -lt 90 ]; do
    if mailbox_exists "$addr"; then
      detail "  mailbox present: $addr"
      return 0
    fi
    out="$(printf '%s\n%s\n' "$pass" "$pass" \
           | docker exec -i mailserver setup email add "$addr" 2>&1)"
    log "  setup email add $addr -> rc=$? ${out:+| $(printf '%s' "$out" | tail -2 | tr '\n' ' ')}"
    if mailbox_exists "$addr"; then
      detail "  mailbox created: $addr"
      return 0
    fi
    # A store the CLI cannot write is not a boot race — `setup email add` never
    # succeeds against it, so retrying the same call for 90 s only delays the
    # report. Recreate once (the entrypoint re-checks / re-inits the accounts
    # file on boot), then keep retrying: a recreated DMS comes back with the
    # store it can use on a bind mount that is writable again.
    if printf '%s' "$out" | grep -qiE 'permission denied|read-only file system|cannot open|unable to (write|create)'; then
      log "  setup email add: account store not writable — recreating mailserver"
      make dok-recreate-mailserver >>"$LOG" 2>&1 || true
      mail_wait_ready
    fi
    # Container down → recreate it (a live one just needs the retry; restarting
    # a booting DMS would reset its own account wait timer).
    if ! docker exec mailserver true >/dev/null 2>&1; then
      log "  mailserver not running — recreating before the next attempt"
      make dok-recreate-mailserver >>"$LOG" 2>&1 || true
      mail_wait_ready
    fi
    sleep 5; i=$((i+5))
  done
  log "  mailbox $addr NOT created after ${i}s (last output above)"
  return 1
}

# nextcloud_setup()'s app-selection entry: a config-driven app set for the
# cloud module, driven by config/cloud/apps.conf (shipped with sane defaults:
# spreed install&enable, app_api disable). The config is the *intent*; this
# reads the live instance once (occ app:list) and applies actions against real
# state — an action already satisfied is skipped silently (idempotent,
# unattended re-runs). The only prompted cases are the ones where the config and
# the live state genuinely disagree in a surprising way: an unknown verb
# (ignored), the same app given two different verbs (proceed / abort), a
# `disable=` on an app that is NOT installed (install&disable / drop), and a
# `remove=` on an installed+enabled app (proceed / drop / resolve) — removal is
# the only destructive action. Runs only when cloud is selected; the resulting
# enabled set is written to $DATA/cloud/recovery/apps.txt (GENERATED, outside
# the repo).
ask_nc_apps() {
  local conf="$REPO/config/cloud/apps.conf"

  # Cloud must be desired; the configured actions then apply.
  mod_on cloud || return 0

  # No config → nothing to do (fresh installs get image defaults only).
  [ -f "$conf" ] || return 0

  # ---------- parse the config ----------
  # Valid verbs: install&enable=, install&disable=, disable=, remove=.
  # Multi-action lines are supported (split on whitespace); bare verbs /
  # comments are ignored; an unknown verb is warned to stderr and ignored.
  declare -A install=() install_dis=() disable=() remove=() seen=() conflict=()
  local line tok verb key
  while IFS= read -r line || [ -n "$line" ]; do
    line="${line%%#*}"                          # strip inline comments
    line="${line#"${line%%[![:space:]]*}"}"     # trim leading whitespace
    line="${line%"${line##*[![:space:]]}"}"     # trim trailing whitespace
    [ -z "$line" ] && continue
    for tok in $line; do
      [[ "$tok" == *"="* ]] || continue         # bare verb → ignore
      verb="${tok%%=*}"; key="${tok#*=}"
      case "$verb" in
        install\&enable)  install["$key"]=1; seen["$key"]=1 ;;
        install\&disable) install_dis["$key"]=1; seen["$key"]=1 ;;
        disable)          disable["$key"]=1; seen["$key"]=1 ;;
        remove)           remove["$key"]=1; seen["$key"]=1 ;;
        *) _note "$(printf '  %sWARN%s config/cloud/apps.conf: unknown verb %s in %s — ignored' "$C_ORANGE" "$C_RST" "'$verb'" "'$tok'")" ;;
      esac
    done
  done < "$conf"

  # ---------- conflicts: same app with two different verbs ----------
  # Fatal unless you explicitly drop them: warn with full details, prompt,
  # abort only if unconfirmed.
  local key cnt
  for key in "${!seen[@]}"; do
    cnt=$(( ${install["$key"]:-0} + ${install_dis["$key"]:-0} + ${disable["$key"]:-0} + ${remove["$key"]:-0} ))
    [ "$cnt" -gt 1 ] && conflict["$key"]=1
  done
  local conflicted="${!conflict[*]}"
  if [ -n "$conflicted" ]; then
    _task_pause
    _note ""
    _note "$(printf '%s┌─ ERROR%s %ssame app has two different verbs%s' "$C_RED" "$C_RST" "$C_GREY" "$C_RST")"
    for key in $conflicted; do
      [ "${install["$key"]:-}" = "1" ] && _note "$(printf '  %s%s%s  install&enable' "$C_RED" "$key" "$C_RST")"
      [ "${install_dis["$key"]:-}" = "1" ] && _note "$(printf '  %s%s%s  install&disable' "$C_RED" "$key" "$C_RST")"
      [ "${disable["$key"]:-}" = "1" ] && _note "$(printf '  %s%s%s  disable' "$C_RED" "$key" "$C_RST")"
      [ "${remove["$key"]:-}" = "1" ] && _note "$(printf '  %s%s%s  remove' "$C_RED" "$key" "$C_RST")"
    done
    _note "$(printf '%s└──────────────────────────────────────────────%s' "$C_RED" "$C_RST")"
    local _abort
    if ! ask_boolean "abort the install?" _abort; then
      _note "no terminal input — aborting"; exit 1
    fi
    [ "$_abort" = "true" ] && exit 1
    _note "$(printf '%sdropping conflicting actions and continuing%s' "$C_ORANGE" "$C_RST")"
    _task_resume
  fi

  # ---------- print the plan ----------
  local ipl ids dis rem
  ipl=$(printf '%s\n' "${!install[@]}" | paste -sd', ' -)
  ids=$(printf '%s\n' "${!install_dis[@]}" | paste -sd', ' -)
  dis=$(printf '%s\n' "${!disable[@]}" | paste -sd', ' -)
  rem=$(printf '%s\n' "${!remove[@]}" | paste -sd', ' -)
  _task_pause
  _note ""
  _note "$(printf '%s┌─ Nextcloud apps%s  %s(config/cloud/apps.conf)%s' "$C_ORANGE" "$C_RST" "$C_GREY" "$C_RST")"
  [ -n "$ipl" ] && _note "$(printf '  %swill install/enable%s   %s' "$C_GREY" "$C_RST" "$ipl")"
  [ -n "$ids" ] && _note "$(printf '  %swill install/disable%s  %s' "$C_GREY" "$C_RST" "$ids")"
  [ -n "$dis" ] && _note "$(printf '  %swill disable%s          %s' "$C_GREY" "$C_RST" "$dis")"
  [ -n "$rem" ] && _note "$(printf '  %swill remove%s           %s' "$C_GREY" "$C_RST" "$rem")"
  _note "$(printf '%s└─────────────────────────────────────────────────────%s' "$C_ORANGE" "$C_RST")"
  # An empty plan means the config has no actionable lines → nothing to do.

  local _confirm
  if ! ask_boolean "Apply configured app actions?" _confirm; then
    _note "app actions skipped (not confirmed)"
    _task_resume
    return 0
  fi
  _task_resume

  # ---------- pre-flight: read the live app state exactly once ----------
  # occ app:list: "Enabled:" / "Disabled:" sections, lines "  - id: version";
  # strip everything after the first colon so "spreed: 24.0.5" matches.
  local ncpid
  ncpid=$(docker ps --format '{{.Names}}' | grep -x nextcloud)
  [ -n "$ncpid" ] || { fail ask_nc_apps "nextcloud container is not running"; return 1; }
  # Timeout a hanging occ; the list is small so 120s is ample.
  occ_out=$(timeout 120 docker exec -u www-data nextcloud php occ app:list --output=plain 2>/dev/null) || {
    fail ask_nc_apps "occ app:list failed (container may still be booting) — see $LOG"
    return 1
  }
  enabled_ids=$(printf '%s' "$occ_out" | awk 'BEGIN{f=0} /^Enabled:/{f=1;next} /^Disabled:/{f=0} f && /^  -/{sub(/^  - /,""); sub(/:.*/, ""); print}')
  disabled_ids=$(printf '%s' "$occ_out" | awk 'BEGIN{f=0} /^Disabled:/{f=1} f && /^  -/{sub(/^  - /,""); sub(/:.*/, ""); print}')
  # $1 = needle, $2.. = app ids (exact match, no word-split corruption)
  in_list() {
    local needle="$1"; shift
    local item
    for item in "$@"; do
      [ "$item" = "$needle" ] && return 0
    done
    return 1
  }

  # ---------- apply install&enable ----------
  for app in "${!install[@]}"; do
    [ "${conflict["$app"]:-}" = "1" ] && continue
    if in_list "$app" $enabled_ids; then
      continue                    # already installed+enabled → skip silently
    elif in_list "$app" $disabled_ids; then
      # Enabled already in the image but reported disabled → operator request wins.
      if ! docker exec -u www-data nextcloud php occ app:enable "$app" >/dev/null 2>&1; then
        _err_note "occ app:enable $app failed — see $LOG"
        fail ask_nc_apps "occ app:enable $app failed"
        continue
      fi
      continue                    # done
    fi
    # Not installed at all → auto-install + auto-enable per operator request
    # (config/cloud/apps.conf): no prompt.
    # Failures are logged and dropped silently; the plan above is authoritative.
    detail "  install&enable='$app' — not present in occ; installing then enabling"
    if ! timeout 120 docker exec -u www-data nextcloud php occ app:install "$app" >>"$LOG" 2>&1; then
      _warn_note "occ app:install $app failed — app not in the appstore and no local app dir; action dropped"
      continue
    fi
    if ! timeout 120 docker exec -u www-data nextcloud php occ app:enable "$app" >>"$LOG" 2>&1; then
      _warn_note "occ app:enable $app failed after install; action dropped"
      continue
    fi
    # If still not in the enabled list after install/enable, retry once (occ
    # can be slow on a cold cache); spreed ships in the image so this handles
    # the case where it appears in occ list only after first boot.
    if ! in_list "$app" $enabled_ids; then
      sleep 15
      occ_out=$(timeout 120 docker exec -u www-data nextcloud php occ app:list --output=plain 2>/dev/null) || true
      enabled_ids=$(printf '%s' "$occ_out" | awk 'BEGIN{f=0} /^Enabled:/{f=1;next} /^Disabled:/{f=0} f && /^  -/{sub(/^  - /,""); sub(/:.*/, ""); print}')
    fi
    detail "  installed + enabled $app"
  done

  # ---------- apply install&disable ----------
  # install&disable= requests an app that should exist but stay OFF: install it
  # first (needed for a fresh DB), then disable it. Already installed (enabled
  # or disabled) → just make sure it is disabled; not in occ at all → install.
  for app in "${!install_dis[@]}"; do
    [ "${conflict["$app"]:-}" = "1" ] && continue
    if in_list "$app" $enabled_ids || in_list "$app" $disabled_ids; then
      :                                   # already present — only ensure disabled
    else
      detail "  install&disable='$app' — not present in occ; installing then disabling"
      if ! timeout 120 docker exec -u www-data nextcloud php occ app:install "$app" >>"$LOG" 2>&1; then
        _warn_note "occ app:install $app failed — app not in the appstore and no local app dir; action dropped"
        continue
      fi
    fi
    if in_list "$app" $enabled_ids; then
      if ! docker exec -u www-data nextcloud php occ app:disable "$app" >/dev/null 2>&1; then
        _err_note "occ app:disable $app failed — see $LOG"
        fail ask_nc_apps "occ app:disable $app failed"
        continue
      fi
    fi
    detail "  installed + disabled $app"
  done

  # ---------- apply disable ----------
  # disable= on an installed app (enabled or already disabled) is the operator's
  # stated intent — apply it, no prompt. Only an app that is NOT installed at all
  # is surprising (nothing to disable) — warn and offer install&disable or skip.
  for app in "${!disable[@]}"; do
    [ "${conflict["$app"]:-}" = "1" ] && continue
    if in_list "$app" $disabled_ids; then
      continue                    # already disabled → skip silently
    elif in_list "$app" $enabled_ids; then
      # Installed and enabled → apply the config's intent without prompting.
      if ! docker exec -u www-data nextcloud php occ app:disable "$app" >/dev/null 2>&1; then
        _err_note "occ app:disable $app failed — see $LOG"
        fail ask_nc_apps "occ app:disable $app failed"
      fi
      continue
    fi
    # Not installed → nothing to disable. Warn and offer to install&disable.
    _task_pause
    _note ""
    _note "$(printf '%s┌─ WARN%s %sdisable=%s but it is not installed%s' "$C_ORANGE" "$C_RST" "$C_GREY" "$app" "$C_RST")"
    _note "$(printf '  live state:  %snot installed%s' "$C_GREY" "$C_RST")"
    _note "  choices:"
    _note "$(printf '    %sinstall&disable%s — install %s, then disable it (keeps it present but off)' "$C_GREEN" "$C_RST" "$app")"
    _note "$(printf '    %sdrop%s            — skip this action (leave nothing)' "$C_GREY" "$C_RST")"
    _note "$(printf '%s└──────────────────────────────────────────────%s' "$C_ORANGE" "$C_RST")"
    local choice
    while true; do
      read -r choice || { _note "no terminal input — dropping action"; _task_count 1; break; }
      _task_count 1
      case "${choice,,}" in
        install\&disable|install|yes) break ;;
        drop|skip|no) break ;;
        *) _note "  unknown choice: $choice" ;;
      esac
    done
    _task_resume
    case "${choice,,}" in
      install\&disable|install|yes)
        if ! timeout 120 docker exec -u www-data nextcloud php occ app:install "$app" >>"$LOG" 2>&1; then
          _warn_note "occ app:install $app failed — app not in the appstore and no local app dir; action dropped"
          continue
        fi
        if ! docker exec -u www-data nextcloud php occ app:disable "$app" >/dev/null 2>&1; then
          _err_note "occ app:disable $app failed — see $LOG"
          fail ask_nc_apps "occ app:disable $app failed"
          continue
        fi
        detail "  installed + disabled $app"
        ;;
      drop|skip|no) : ;;
    esac
  done

  # ---------- apply remove ----------
  for app in "${!remove[@]}"; do
    [ "${conflict["$app"]:-}" = "1" ] && continue
    if in_list "$app" $disabled_ids; then
      continue                    # disabled → skip silently
    elif ! in_list "$app" $enabled_ids; then
      continue                    # not installed → skip silently (occ app:remove is a no-op)
    fi
    # Installed+enabled: remove silently per config intent.
    if ! docker exec -u www-data nextcloud php occ app:remove "$app" >/dev/null 2>&1; then
      _err_note "occ app:remove $app failed — see $LOG"
      fail ask_nc_apps "occ app:remove $app failed"
      continue
    fi
  done

  # ---------- record the resulting enabled set ----------
  # The installer is the source of truth: write the enabled snapshot so a fresh
  # DB can reproduce exactly what the operator configured; make nc-capture keeps
  # a read-only mirror for diffs against config/cloud/apps.conf.
  mkdir -p "$MANIFEST_DIR"
  {
    echo "# GENERATED by install.sh from config/cloud/apps.conf ($(date -Is)) — do not edit; re-run install to refresh."
    echo "# Format: one app id per line (occ app:list --enabled)."
    docker exec -u www-data nextcloud php occ app:list --enabled 2>/dev/null \
      | grep -oE '^  - [^:]+' | sed -E 's/^  - ([^:]+).*/\1/'
  } > "$MANIFEST_DIR/apps.txt"
  detail "  recorded enabled apps ($MANIFEST_DIR/apps.txt): $(wc -l < "$MANIFEST_DIR/apps.txt" | tr -d ' ')"
  return 0
}
# outbound SMTP (nextcloud@$DOMAIN sender mailbox), background cron. All
# steps are idempotent (safe to re-run; never clobbers operator settings).
# Requires the nextcloud + mailserver containers (called after containers_up).
nextcloud_setup() {
  cd "$REPO" || exit 1
  . modules/nextcloud/.env
  # The image entrypoint only installs Nextcloud while /var/www/html has no
  # version.php. A first attempt that fails (empty NEXTCLOUD_ADMIN_* from a
  # skipped seed, DB not yet up, …) still leaves version.php behind, and every
  # later start reads that as "already at the image version" and silently
  # skips BOTH install and upgrade: the container reports healthy, occ reports
  # "installed: false", and no occ step below ever runs (2026-09-25). So do
  # the install here when occ says it is missing — same options the entrypoint
  # would use, taken from the same .env.
  if ! docker exec -u www-data nextcloud php occ status 2>/dev/null | grep -q "installed: true"; then
    log "  nextcloud reports not-installed — running occ maintenance:install"
    if docker exec -u www-data nextcloud php occ maintenance:install -n \
         --admin-user "${NEXTCLOUD_ADMIN_USER:-admin}" \
         --admin-pass "${NEXTCLOUD_ADMIN_PASSWORD:-}" \
         --data-dir /data \
         --database pgsql --database-name "$POSTGRES_DB" \
         --database-user "$POSTGRES_USER" --database-pass "$POSTGRES_PASSWORD" \
         --database-host "$POSTGRES_HOST" >>"$LOG" 2>&1; then
      log "  nextcloud installed"
      # occ does not apply NEXTCLOUD_TRUSTED_DOMAINS (the entrypoint does) —
      # without this entry https://cloud.$DOMAIN answers 400 untrusted domain.
      docker exec -u www-data nextcloud php occ config:system:set trusted_domains 1 \
        --value "cloud.$DOMAIN" >/dev/null 2>&1 || true
    else
      fail nextcloud_setup "occ maintenance:install failed — see $LOG"
    fi
  fi
  # Then wait for a usable instance: a cold cache (fresh image pull + the
  # ~3 min Caddy build hogging the box) blew the old 3-minute budget, so every
  # occ step below — Talk signaling/TURN, SMTP, cron — silently never ran
  # (2026-09-25). 30 minutes now, with a secondary HTTP probe to cloud.$DOMAIN
  # and a per-call occ timeout so a hanging occ never stalls the loop.
  local i=0
  while [ $i -lt 1800 ]; do
    if timeout 20 docker exec -u www-data nextcloud php occ status 2>/dev/null | grep -q "installed: true"; then
      break
    fi
    if timeout 10 curl -sk "https://cloud.$DOMAIN/" >/dev/null 2>&1; then
      break     # NC answers HTTPS → ready, even if occ is still warming the cache
    fi
    [ $((i % 30)) -eq 0 ] && log "  waiting for nextcloud to finish installing (${i}s)"
    sleep 2; i=$((i+2))
  done
  if ! timeout 20 docker exec -u www-data nextcloud php occ status 2>/dev/null | grep -q "installed: true"; then
    fail nextcloud_setup "nextcloud not installed/ready after 30 min"
    return
  fi

  # Config-driven app selection for the cloud module (config/cloud/apps.conf).
  # Now that the instance is confirmed installed, ask the operator which apps to
  # install/enable/disable/remove based on the shipped occ app list.
  ask_nc_apps

  # SMTP wiring is gated on the mail module — `mod_on mail` is the single
  # definition of that test, so this step can never disagree with what the
  # module record in install.state says or with the mailbox/recheck arms.
  . modules/nextcloud/.env
  if mod_on mail; then
    mailbox_add "nextcloud@$DOMAIN" "${SMTP_PASSWORD:-}" \
      || fail nextcloud_setup "mailbox nextcloud@$DOMAIN not created"
  else
    log "  mail module disabled — skipping mailbox nextcloud@$DOMAIN"
  fi

  # trusted_proxies must be a real ARRAY (NC 34 setup check) — the image
  # env TRUSTED_PROXIES writes a comma-joined string into index 0, which
  # breaks the brute-force throttle. The compose no longer carries it; set
  # it here as indexed entries (Caddy's net subnet + Cloudflare edge ranges).
  docker exec -u www-data nextcloud php occ config:system:delete trusted_proxies >/dev/null 2>&1 || true
  local p i=0
  for p in 172.22.0.0/16 173.245.48.0/20 103.21.244.0/22 103.22.200.0/22 103.31.4.0/22 141.101.64.0/18 108.162.192.0/18 190.93.240.0/20 188.114.96.0/20 197.234.240.0/22 198.41.128.0/17 162.158.0.0/15 104.16.0.0/13 104.24.0.0/14 172.64.0.0/13 131.0.72.0/22 2400:cb00::/32 2606:4700::/32 2803:f800::/32 2405:b500::/32 2405:8100::/32 2a06:98c0::/29 2c0f:f248::/32; do
    docker exec -u www-data nextcloud php occ config:system:set trusted_proxies "$i" --value "$p" >/dev/null 2>&1
    i=$((i+1))
  done

  # NC SMTP settings — host/port/name/from/domain only when unset (never
  # clobber operator config); secure + authtype fixed unconditionally (the
  # 2026-08-31 "Email could not be sent" cause was secure=ssl on port 587).
  # Output redirected: occ config:system:set echoes secret values to stdout.
  if [ -z "$(docker exec -u www-data nextcloud php occ config:system:get mail_smtphost 2>/dev/null | tr -d '\n')" ]; then
    docker exec -u www-data nextcloud php occ config:system:set mail_smtphost --value "mail.$DOMAIN" >/dev/null 2>&1
    docker exec -u www-data nextcloud php occ config:system:set mail_smtpport --value 587 >/dev/null 2>&1
    docker exec -u www-data nextcloud php occ config:system:set mail_smtpname --value "nextcloud@$DOMAIN" >/dev/null 2>&1
    docker exec -u www-data nextcloud php occ config:system:set mail_smtppassword --value "$SMTP_PASSWORD" >/dev/null 2>&1
    docker exec -u www-data nextcloud php occ config:system:set mail_from_address --value nextcloud >/dev/null 2>&1
    docker exec -u www-data nextcloud php occ config:system:set mail_domain --value "$DOMAIN" >/dev/null 2>&1
  fi
  docker exec -u www-data nextcloud php occ config:system:set mail_smtpsecure --value tls >/dev/null 2>&1
  docker exec -u www-data nextcloud php occ config:system:set mail_smtpauthtype --value LOGIN >/dev/null 2>&1
  # Without mail_smtpauth=true NC connects anonymously and the submission
  # server rejects every send ("Client host rejected: Access denied") — the
  # UI test email fails even though the credentials are valid.
  docker exec -u www-data nextcloud php occ config:system:set mail_smtpauth --value true >/dev/null 2>&1

  # Single-PHP instance: serverid (int 0-511) silences the "Configuration
  # server ID" setup check; AppAPI is disabled — no external apps are used
  # (the "AppAPI default deploy daemon" check only fires while it's enabled).
  if [ -z "$(docker exec -u www-data nextcloud php occ config:system:get serverid 2>/dev/null | tr -d '\n')" ]; then
    docker exec -u www-data nextcloud php occ config:system:set serverid --value 1 --type integer >/dev/null 2>&1 || true
  fi
  # Talk signaling — ONE entry (the public URL): NC 34 deprecates multiple
  # high-performance backends. Clients get wss://talk.$DOMAIN/signaling; the
  # signaling server reaches NC back via its own [backend1] urls (extra_hosts),
  # so no internal URL registration is needed.
  local sig
  sig=$(docker exec -u www-data nextcloud php occ talk:signaling:list 2>/dev/null)
  if ! echo "$sig" | grep -q "https://talk.$DOMAIN/signaling"; then
    docker exec -u www-data nextcloud php occ talk:signaling:add "https://talk.$DOMAIN/signaling" "$SIGNALING_SECRET" >/dev/null 2>&1 || true
  fi
  docker exec -u www-data nextcloud php occ talk:signaling:remove "http://172.22.0.12:8080" >/dev/null 2>&1 || true

  # Talk TURN/STUN — udp+tcp on 3478, tls on 5349 (secret matches turnserver.conf).
  local trn
  trn=$(docker exec -u www-data nextcloud php occ talk:turn:list 2>/dev/null)
  # talk:turn:add <schemes> <server> <protocols> — protocols are POSITIONAL;
  # the old --udp/--tcp flags don't exist, so the call always failed and TURN
  # was never registered.
  if ! echo "$trn" | grep -q "talk.$DOMAIN:3478"; then
    docker exec -u www-data nextcloud php occ talk:turn:add turn "talk.$DOMAIN:3478" "udp,tcp" --secret "$TURN_SECRET" >/dev/null 2>&1 || true
  fi
  if ! echo "$trn" | grep -q "talk.$DOMAIN:5349"; then
    docker exec -u www-data nextcloud php occ talk:turn:add turns "talk.$DOMAIN:5349" "tcp" --secret "$TURN_SECRET" >/dev/null 2>&1 || true
  fi

  # Background jobs via the host cron (config/cron/nextcloud, installed by install-config).
  docker exec -u www-data nextcloud php occ background:cron >/dev/null 2>&1 || true

  # Silence the recurring "Skipping updater backup clean-up" warning: the
  # cleanup job expects /data/updater-<instanceid>/backups to exist.
  IID=$(docker exec -u www-data nextcloud php occ config:system:get instanceid 2>/dev/null | tr -d '\n')
  [ -n "$IID" ] && docker exec -u www-data nextcloud sh -c "mkdir -p /data/updater-$IID/backups" >/dev/null 2>&1 || true

  # Recovery manifest: users + quotas ($DATA/cloud/recovery/users.txt, kept
  # OUTSIDE the repo — instance state, generated by `make nc-capture`). Missing
  # users are created with a generated password printed ONCE at the end (the
  # pre-wipe passwords lived in the wiped DB — hand the new ones to the users).
  if [ -f "$MANIFEST_DIR/users.txt" ]; then
    while IFS='|' read -r uid quota email disp _; do
      [ -n "$uid" ] || continue
      case "$uid" in \#*) continue ;; esac
      if ! docker exec -u www-data nextcloud php occ user:list 2>/dev/null | grep -q "^  - $uid:"; then
        NP=$(openssl rand -base64 12 | tr -d '/+=' | head -c 12)
        docker exec -e OC_PASS="$NP" -u www-data nextcloud php occ user:add --password-from-env "$uid" >/dev/null 2>&1 \
          && msg "[install] new user $uid — password: $NP (share with them)"
      fi
      [ -n "$quota" ] && docker exec -u www-data nextcloud php occ user:setting "$uid" files quota "$quota" >/dev/null 2>&1
      [ -n "$email" ] && docker exec -u www-data nextcloud php occ user:setting "$uid" settings email "$email" >/dev/null 2>&1
      [ -n "$disp" ] && docker exec -u www-data nextcloud php occ user:setting "$uid" settings displayname "$disp" >/dev/null 2>&1
    done < "$MANIFEST_DIR/users.txt"
  fi

  # The vhost Host must be trusted or NC 400s every request on it. The compose
  # env NEXTCLOUD_TRUSTED_DOMAINS seeds cloud.$DOMAIN on a fresh DB — writing
  # the bare $DOMAIN into index 1 clobbers it.
  if ! docker exec -u www-data nextcloud php occ config:system:get trusted_domains 2>/dev/null | grep -qx "cloud.$DOMAIN"; then
    docker exec -u www-data nextcloud php occ config:system:set trusted_domains 1 --value "cloud.$DOMAIN" >/dev/null 2>&1 || true
  fi

  # Recovery manifest: apps enabled beyond the image defaults
  # ($DATA/cloud/recovery/apps.txt).
  if [ -f "$MANIFEST_DIR/apps.txt" ]; then
    while read -r app; do
      [ -n "$app" ] || continue
      case "$app" in \#*) continue ;; esac
      docker exec -u www-data nextcloud php occ app:enable "$app" >/dev/null 2>&1 || true
    done < "$MANIFEST_DIR/apps.txt"
  fi

  # Fresh installs ship with pending maintenance work that the setup check
  # surfaces as warnings — run it all up front so a fresh install is clean:
  #   - mimetype migrations (occ maintenance:repair --include-expensive)
  #   - missing DB indices/columns/primary keys (the mail app adds several)
  docker exec -u www-data nextcloud php occ maintenance:repair --include-expensive >/dev/null 2>&1 || true
  docker exec -u www-data nextcloud php occ db:add-missing-indices >/dev/null 2>&1 || true
  docker exec -u www-data nextcloud php occ db:add-missing-columns >/dev/null 2>&1 || true
  docker exec -u www-data nextcloud php occ db:add-missing-primary-keys >/dev/null 2>&1 || true

  # Recovery manifest: default quota for new users (cloud/recovery/default-quota)
  if [ -f "$MANIFEST_DIR/default-quota" ]; then
    DQ=$(grep -v '^#' "$MANIFEST_DIR/default-quota" | head -1)
    [ -n "$DQ" ] && docker exec -u www-data nextcloud php occ config:app:set files default_quota --value "$DQ" >/dev/null 2>&1 || true
  fi

  # Recovery manifest: groups (cloud/recovery/groups.txt)
  if [ -f "$MANIFEST_DIR/groups.txt" ]; then
    while IFS='|' read -r grp members _; do
      [ -n "$grp" ] || continue
      case "$grp" in \#*) continue ;; esac
      docker exec -u www-data nextcloud php occ group:addgroup "$grp" >/dev/null 2>&1 || true
      for m in ${members//,/ }; do
        [ -n "$m" ] && docker exec -u www-data nextcloud php occ group:adduser "$grp" "$m" >/dev/null 2>&1 || true
      done
    done < "$MANIFEST_DIR/groups.txt"
  fi

  # Verify what the smoke/operational docs assert. `occ` can be flaky for a few
  # seconds right after a container start (DB warm-up), so retry each check
  # before treating it as a real failure.
  occ_check() {
    local pattern="$1"; shift
    local attempt=0 rc=1
    # 30 attempts x 2 s (60 s) covers the occ DB warm-up window after a
    # container restart (occ status can return fast while a talk:turn:list hit a
    # transient lock), so a warm-up race never kills the install.
    while [ $attempt -lt 30 ]; do
      if "$@" | grep -q "$pattern"; then rc=0; break; fi
      attempt=$((attempt+1)); [ $attempt -lt 30 ] && sleep 2
    done
    return $rc
  }
  # The wiring only counts as done once ALL of it is visible. A slow boot is a
  # matter of TIME, not an error: verify, and if the wiring is simply not visible
  # yet, re-apply it (idempotent) and wait again — never surface the timeout as
  # an error tag that then clears on a re-check (2026-10-15: 'occ wiring
  # incomplete' was raised, then solved itself; that is a race, not a fault).
  nc_wiring_ok() {
    # SMTP is only wired when the mail module is enabled (see the mailbox step).
    if mod_on mail; then
      occ_check "mail.$DOMAIN" docker exec -u www-data nextcloud php occ config:system:get mail_smtphost 2>/dev/null \
        || return 1
    fi
    occ_check "https://talk.$DOMAIN/signaling" docker exec -u www-data nextcloud php occ talk:signaling:list 2>/dev/null \
      || return 1
    occ_check "talk.$DOMAIN:3478" docker exec -u www-data nextcloud php occ talk:turn:list 2>/dev/null \
      || return 1
    return 0
  }
  if ! nc_wiring_ok; then
    log "  nextcloud occ wiring not confirmed yet — re-applying it and waiting"
    nextcloud_occ_remediate
    nc_wiring_ok || fail nextcloud_setup "occ wiring not confirmed after re-apply"
  fi
}

