recheck() {
  case "$1" in
    apt) command -v docker >/dev/null 2>&1 && docker compose version >/dev/null 2>&1 && dpkg -s git curl make sudo dnsmasq ufw jq apache2-utils sqlite3 python3-yaml >/dev/null 2>&1 ;;
    goose) command -v goose >/dev/null 2>&1 || [ -x /usr/local/bin/goose ] ;;
    user) id -u "root" >/dev/null 2>&1 ;;
    ssh_keys) [ -s /root/.ssh/authorized_keys ] ;;
    github_key) [ -s /root/.ssh/github_key ] ;;
    github_auth) github_auth_ok && github_push ;;
    render) bash "$REPO/scripts/render/render-all.sh" >/dev/null 2>&1 ;;
    tailscale) command -v tailscale >/dev/null 2>&1 ;;
    tailscale_up) tailscale ip -4 >/dev/null 2>&1 ;;
    ts_ip) [ -n "$(tailscale ip -4 2>/dev/null | head -1)" ] ;;
    install_config) systemctl is-active --quiet ttyd dnsmasq goose ;;
    fail2ban) systemctl is-active --quiet fail2ban && fail2ban-client status sshd >/dev/null 2>&1 ;;
    caddy) docker ps --format '{{.Names}}' | grep -qx caddy ;;
    nextcloud) docker ps --format '{{.Names}}' | grep -qx nextcloud && docker ps --format '{{.Names}}' | grep -qx talk-hpb && docker ps --format '{{.Names}}' | grep -qx talk-relay ;;
    nextcloud_db) docker ps --format '{{.Names}}' | grep -qx postgresql ;;
    vaultwarden) docker ps --format '{{.Names}}' | grep -qx vaultwarden ;;
    kuma) docker ps --format '{{.Names}}' | grep -qx uptimekuma ;;
    mailserver) docker ps --format '{{.Names}}' | grep -qx mailserver && docker ps --format '{{.Names}}' | grep -qx roundcube ;;
    datadirectory) if docker exec -w /var/www/html nextcloud php occ status 2>/dev/null | grep -q "installed: true"; then [ "$(docker exec -w /var/www/html nextcloud php occ config:system:get datadirectory 2>/dev/null | tr -d '\n')" = "/data" ]; else true; fi ;;
    kuma_admin) [ "$(docker exec uptimekuma sqlite3 /app/data/kuma.db "SELECT COUNT(*) FROM user WHERE username='admin';" 2>/dev/null | tr -d '\n')" = "1" ] ;;
    kuma_seed) [ "$(docker exec uptimekuma sqlite3 /app/data/kuma.db "SELECT COUNT(*) FROM monitor;" 2>/dev/null | tr -d '\n')" -gt 0 ] ;;
    zone) [ -n "$(curl -s -H "Authorization: Bearer $CF_API_TOKEN" "https://api.cloudflare.com/client/v4/zones?name=$DOMAIN" | jq -r '.result[0].id // empty')" ] ;;
    dns_*) local h=${1#dns_}; [ -n "$(curl -s -H "Authorization: Bearer $CF_API_TOKEN" "https://api.cloudflare.com/client/v4/zones/$ZONE_ID/dns_records?type=A&name=$h.$DOMAIN" | jq -r '.result[0].id // empty')" ] ;;
    cert_*) local h=${1#cert_}; echo | timeout 10 openssl s_client -connect 127.0.0.1:443 -servername "$h.$DOMAIN" 2>/dev/null | openssl x509 -noout -issuer 2>/dev/null | grep -q "Let's Encrypt" ;;
    sweep) [ -z "$(sweep_hits)" ] ;;
    sslmode) ssl_mode_full ;;
    nextcloud_setup) docker exec -u www-data nextcloud php occ config:system:get mail_smtphost 2>/dev/null | grep -q "mail.$DOMAIN" && docker exec -u www-data nextcloud php occ talk:signaling:list 2>/dev/null | grep -q "https://talk.$DOMAIN/signaling" && docker exec -u www-data nextcloud php occ talk:turn:list 2>/dev/null | grep -q "talk.$DOMAIN:3478" && docker exec -u www-data nextcloud php occ config:system:get trusted_domains 2>/dev/null | grep -qx "cloud.$DOMAIN" ;;
    dkim_setup)      dig +short TXT "mail._domainkey.$DOMAIN" @"$(dig +short NS "$DOMAIN" | head -1)" 2>/dev/null | grep -qE 'p=[A-Za-z0-9+/=]{100,}' ;;
    vaultwarden_setup) docker exec mailserver setup email list 2>/dev/null | grep -qiE "^[* ] *vaultwarden@$DOMAIN( |\$|\[)" ;;
    *) false ;;
  esac
}

is_expected() {
  case "$1" in
    zone|clone|sslmode|github_auth) return 0 ;;  # input prerequisites / dashboard steps the script can't do
    *) return 1 ;;
  esac
}

resolve_errors() {
  local remaining=("${ERR_TAGS[@]}")
  while [ ${#remaining[@]} -gt 0 ]; do
    echo ""
    local exp=() unexp=()
    for tag in "${remaining[@]}"; do
      if is_expected "$tag"; then exp+=("$tag"); else unexp+=("$tag"); fi
    done
    if [ ${#exp[@]} -gt 0 ]; then
      echo " Manual steps (expected):"
      for i in "${!exp[@]}"; do
        echo "   $((i+1)). ${exp[$i]}"
        echo "      problem: $(problem "${exp[$i]}")${ERR_DETAIL[${exp[$i]}]:+ (${ERR_DETAIL[${exp[$i]}]})}"
        echo "      hint: $(hint "${exp[$i]}")"
      done
    fi
    if [ ${#unexp[@]} -gt 0 ]; then
      echo " Unexpected errors (${#unexp[@]}):"
      for i in "${!unexp[@]}"; do
        echo "   $((i+1)). ${unexp[$i]}"
        echo "      problem: $(problem "${unexp[$i]}")${ERR_DETAIL[${unexp[$i]}]:+ (${ERR_DETAIL[${unexp[$i]}]})}"
        echo "      hint: $(hint "${unexp[$i]}")"
      done
    fi
    read -rp "Fix / complete the items above, then press Enter to re-check (Ctrl-C aborts): " input \
      || { echo "No terminal input — aborting."; exit 1; }
    local still=()
    for tag in "${remaining[@]}"; do
      if recheck "$tag"; then
        echo "   ✓ solved: $tag — $(problem "$tag")"
      else
        still+=("$tag")
      fi
    done
    remaining=("${still[@]}")
  done
  ERR_TAGS=()
  write_modules_conf
  finalize_hardening
  success_block
  ask_optimize
}

# ── Optional follow-up — only ever reached after a FULLY green run ────────
# optimize.sh is a separate tool (the VPS performance pass), so it is offered,
# never assumed. It is idempotent — re-running it is a no-op — which is why a
# re-run of install.sh may offer it again.
ask_optimize() {
  local answer rc
  [ -f "$REPO/scripts/ops/optimize.sh" ] || return 0
  while :; do
    read -rp "Also run the VPS performance pass (kernel, swap, disk tuning) now? (yes/no): " answer || return 0
    case "${answer,,}" in
      yes|y|true)  break ;;
      no|n|false)  log "  optimize.sh skipped — run it later: bash $REPO/scripts/ops/optimize.sh"; return 0 ;;
      *)           echo "   answer yes or no." ;;
    esac
  done
  log "  running scripts/ops/optimize.sh --yes (its output goes to $LOG)"
  bash "$REPO/scripts/ops/optimize.sh" --yes 2>&1 | tee -a "$LOG"
  rc=${PIPESTATUS[0]}
  if [ "$rc" = 0 ]; then
    log "  optimize.sh done"
  else
    log "  optimize.sh exited $rc — it is optional and can be re-run any time: bash $REPO/scripts/ops/optimize.sh"
  fi
}

finalize_hardening() {
  # Runs once every error is resolved: if a key exists now, harden sshd
  # (phase 1 skipped it when no key was present at install time).
  if [ -s /root/.ssh/authorized_keys ]; then
    printf 'PasswordAuthentication no\nPermitRootLogin prohibit-password\nAllowUsers root\n' \
      > /etc/ssh/sshd_config.d/50-cloud-init.conf
    chmod 600 /etc/ssh/sshd_config.d/50-cloud-init.conf
    systemctl restart sshd >/dev/null 2>&1 || true
  fi
  # Close the temporary installer-session SSH rule (tailnet access stays).
  local ip="${INSTALLER_SSH_IP:-}"
  if [ -n "$ip" ] && [ "$ip" != "$(tailscale ip -4 2>/dev/null | head -1)" ]; then
    ufw --force delete allow from "$ip" to any port 22 proto tcp >/dev/null 2>&1 || true
    ufw delete allow from "$ip" to any port 22 proto tcp >/dev/null 2>&1 || true
    log "  removed the temporary installer SSH allow for $ip (root@$NODE_NAME over the tailnet remains the entry point)"
  fi
}

