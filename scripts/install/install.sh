#!/bin/bash
# $NODE_NAME install.sh — root-only, plug-and-play new-machine installer.
#
# ALL inputs are collected up front, in one fixed order, before any install
# work, and each is persisted immediately (so an abort mid-run leaves the
# answers for a resume). Order: continue-gate, apply-previous-answers (only when
# state exists), GitHub collaborator opt-in (+ commit identity + automatic key
# verification), device SSH key, Tailscale auth key, Cloudflare API token,
# domain, modules (one space-separated line). Every affirmation takes only the
# literal words `yes`/`no` (no shortcut, no default); the answer is recorded as
# the boolean true/false. Then it runs unattended as a fixed 11-task checklist
# (grey [WAIT] -> animated orange [TASK] -> green [DONE] / red [ERROR]; a failed
# task is marked, the run continues to the end, and the errors are reported
# after): host services, docker, tailscale, the full stack — Nextcloud (app +
# PostgreSQL + Redis + Talk HPB/TURN), Caddy, Vaultwarden, Uptime Kuma, Docker
# Mailserver + Roundcube — Cloudflare DNS records, and LE cert issuance. The repo
# already carries the canonical <domain> naming (modules/<domain>/,
# vhosts/<host>.caddy); no legacy renames are applied.
#
# Fully autonomous: the Kuma admin account is created
# automatically (the admin passwords are printed once in the final summary —
# nothing is written to disk), and no manual confirmation steps block success —
# the only follow-ups are printed in the summary (Tailscale split-DNS, mailboxes).
# The only step that waits is the opt-in GitHub remote access: the installer
# holds until the key it minted is authorized, verified AUTOMATICALLY (it polls
# ssh until GitHub accepts the key — no manual "press Enter to re-check").
# Prerequisites checked up front: the Cloudflare zone must exist. The repo is
# PUBLIC and is cloned over HTTPS — the clone needs no GitHub key; the key the
# opt-in step mints is for PUSHING to the operator's own repos.
#
# Errors are collected with tags, each shown as a "problem" plus a separate
# "hint". Manual dashboard steps are grouped as expected; real failures as
# unexpected. No success message is printed until every error is resolved:
# after the setup you get a numbered list of what's still failing, and each
# time you press Enter the script re-checks them, prints the solved ones
# once, and the remaining ones — until all are green.
#
# Entry point: root@$NODE_NAME is the ONLY way in (key-only SSH over the
# tailnet). The installer runs entirely as root — no sudo user, no hand-off.
#
# Usage:
#   scp scripts/install/install.sh root@$NODE_NAME:
#   ssh root@$NODE_NAME
#   bash install.sh
#
# Paths: the repo lives at $REPO ($ROOT); every external,
# untracked artefact (data, modules, databases, uploads) lives under $DATA
# ($ROOT/data), which .gitignore excludes.

. "$(dirname "$(readlink -f "$0")")/../lib/instance.sh" 2>/dev/null || true

set -uo pipefail

# The checkout path is DERIVED from this script's location — never
# hardcoded — so the repo can live anywhere and be renamed
# ($NODE_NAME -> kefoCloud) without editing any script.
REPO="$(cd "$(dirname "$(readlink -f "$0")")/../.." && pwd)"
# Every other part of the repo (Makefile, scripts/*) calls the checkout root
# $ROOT; this installer is the one place that names it $REPO. Both must exist:
# the $ROOT/data paths below aborted the run under `set -u`.
ROOT="$REPO"
DATA="$REPO/data"

# GITHUB_USER owns the repos. instance.conf wins (scripts/lib/instance.sh loaded
# it above); otherwise the checkout's own origin remote is the truth. The
# lib's placeholder fallback must never stand in for it — an install that used
# it wrote GITHUB_USER= into instance.conf (leaving {{GITHUB_USER}} unresolved in
# the rendered vhosts/logrotate rule) AND rewrote origin to
# https://github.com/exampleuser/$REPO_NAME.git, clobbering the real remote.
if [ -z "${GITHUB_USER:-}" ] || [ "$GITHUB_USER" = "exampleuser" ]; then
  _owner="$(git -C "$REPO" remote get-url origin 2>/dev/null \
            | sed -nE 's#^(git@github\.com:|https?://github\.com/)([^/]+)/.*#\2#p')"
  [ -n "$_owner" ] && GITHUB_USER="$_owner"
  unset _owner
fi

# Canonical node name for this project: the repo is kefoCloud and the sole login
# is root@<the machine name>. This installer is the ONLY place the machine is
# renamed — it sets the static hostname to $NODE_NAME (task_packages) and writes
# HOSTNAME=$NODE_NAME into data/instance.conf, so every other script derives the
# name from there rather than hardcoding it. Hardcoded here exceptionally; the
# tailnet node adopts this hostname automatically, so no explicit rename is needed.
NODE_NAME="kefomachine"
RENDER_DIR="$DATA/rendered"
# NC recovery manifests live OUTSIDE the repo tree ($DATA/cloud/recovery —
# instance state generated by `make nc-capture`; gitignored via /data/).
MANIFEST_DIR="$DATA/cloud/recovery"
# $LOG_DIR (EVERY log this project writes: install, uninstall and any module
# log) is repo-relative (data/logs), so the whole namespace sits next to the
# instance it describes and one logrotate rule bounds it. No $GITHUB_USER
# namespace and no fallback.
#
# The installer's OWN state is $INSTALL_STATE (data/install.state, mode 0600),
# repo-relative — it holds the CF token + Tailscale key, so it is never
# world-readable. install.sh is its SOLE writer (including the `finished`
# checkpoint); every reader (make smoke / make fetch / scripts/lib/modules.sh)
# only reads it.
LOG_DIR="$DATA/logs"
# INSTALL_STATE is the ONE artefact every reader uses, and this script is its
# sole writer. Sourcing this file for a harness (`bash -c '. install.sh'`) used
# to make its save_state calls write the LIVE state — which is what recorded a
# finished install as pending. Tests must point INSTALL_STATE somewhere else.
INSTALL_STATE="${INSTALL_STATE:-$DATA/install.state}"
FINISHED=false
CHECKPOINT_OPEN=
LOG="$LOG_DIR/install.log"
ERR_TAGS=()
declare -A ERR_DETAIL=()

# ────────────────────────── output + logging ───────────────────────────────
# TWO channels, one rule: $LOG gets EVERYTHING, the console gets only what a
# human watching the run needs.
#
#   log()    — the full record: timestamped, appended to $LOG ONLY. Every step
#              (even ones the console never shows) goes through this, so the log
#              is a complete debug history of the run.
#   detail() — same channel as log(): verbose detail that belongs in the log
#              and never on the console (secrets, per-record DNS chatter,
#              long decision trails).
#   msg()    — the CONSOLE: timestamped line on stdout AND appended to $LOG.
#              Reserved for things an operator must see live — phase titles,
#              warnings, state changes, and the final summary. Everything else
#              is log()-only (a fresh run shows phases + prompts, not a
#              debugging history).
#
# The log is truncated at the START of every run (main() calls init_log), so one
# file always describes exactly one run. Timestamps are purple on a TTY; the
# persistent status bar's seconds/phase are orange. Both are plain when the
# output is not a terminal or NO_COLOR is set (pipes, cron, CI).
C_PURPLE=$'\033[35m' C_ORANGE=$'\033[33m' C_GREEN=$'\033[32m' C_RED=$'\033[31m' C_GREY=$'\033[90m' C_RST=$'\033[0m'
if [ ! -t 1 ] || [ -n "${NO_COLOR:-}" ]; then C_PURPLE= C_ORANGE= C_GREEN= C_RED= C_GREY= C_RST=; fi
_tstamp() { printf '%s[%s]%s' "$C_PURPLE" "$(date +%H:%M:%S)" "$C_RST"; }
log()    { printf '%s %s\n' "$(_tstamp)" "$*" >>"$LOG"; }
detail() { log "$@"; }
# msg never uses `tee`: the purple escapes must land on the console but NOT in
# the log file (a log full of escape codes is unreadable and un-greppable).
# While the live task checklist owns the screen, msg is log-only — nothing may
# print between the task rows.
msg() {
  printf '[%s] %s\n' "$(date +%H:%M:%S)" "$*" >>"$LOG"
  [ -n "${TASK_ACTIVE:-}" ] && return 0
  printf '%s %s\n' "$(_tstamp)" "$*"
}
fail() {
  local t
  for t in "${ERR_TAGS[@]:-}"; do [ "$t" = "$1" ] && return 0; done  # no duplicates across runs
  ERR_TAGS+=("$1"); ERR_DETAIL[$1]="${2:-}"
  TASK_ERR=1
  log "  ERROR: $(problem "$1")${2:+ ($2)}"
}

# A logged note surfaced in the post-install summary but NOT a success blocker
# (used for non-fatal GitHub-push failures and similar soft warnings).
warn() {
  log "  WARN: $(problem "$1")${2:+ ($2)}"
  ERR_WARN_TAGS+=("$1")
}

ERR_WARN_TAGS=()

# ─────────────────────── the installation task checklist ───────────────────
# One fixed list, printed once as a live checklist. Each row starts as [WAIT]
# (grey), becomes an animated [TASK] (orange) while it runs, and ends as [DONE]
# (green) or [ERROR] (red). A failed task is marked, the run CONTINUES through
# the remaining tasks, and every error is reported at the end. Nothing prints
# between the task rows (msg is muted while TASK_ACTIVE is set); each step's own
# output goes to $LOG. On a non-TTY run the animation is skipped and each row is
# printed once, when it finishes.
TASK_NAMES=(
  "Dependent Packages" "SSH Hardening" "Firewall Restriction"
  "Tailscale Connectivity" "Docker Framework" "Docker Containers"
  "Repository Management" "DNS Records" "SSL Certificates"
  "Module Contents" "Smoke Pass"
)
TASK_TOTAL=${#TASK_NAMES[@]}
declare -a TASK_STATE=() TASK_TS=()
TASK_CUR=-1 TASK_ACTIVE= TASK_DRAWN= ANIM_PID= ANIM_POS=0 TASK_ERR=
_TAIL=0 _ANIM_PAUSE=

# The current task's status column: an 8-wide field with ONE green `$` that
# ping-pongs back and forth (0..7..1), inside purple brackets.
_anim_field() {
  local p=$(( ANIM_POS % 14 )); [ "$p" -gt 7 ] && p=$(( 14 - p ))
  local k out=""
  for k in 0 1 2 3 4 5 6 7; do
    if [ "$k" = "$p" ]; then out="${out}${C_GREEN}\$${C_PURPLE}"; else out="${out} "; fi
  done
  printf '%s' "$out"
}
# One newline-terminated row for task $1.
_task_row() {
  local i="$1"
  local st="${TASK_STATE[$i]:-wait}" ts="${TASK_TS[$i]}" name="${TASK_NAMES[$i]}"
  case "$st" in
    done)  printf '%s[%s]%s %s[DONE]%s %s\n'  "$C_PURPLE" "$ts" "$C_RST" "$C_GREEN" "$C_RST" "$name" ;;
    error) printf '%s[%s]%s %s[ERROR]%s %s\n' "$C_PURPLE" "$ts" "$C_RST" "$C_RED"   "$C_RST" "$name" ;;
    run)   printf '%s[%s]%s %s[TASK]%s %s\n'  "$C_PURPLE" "$(_anim_field)" "$C_RST" "$C_ORANGE" "$C_RST" "$name" ;;
    *)     printf '%s[%s]%s %s[WAIT]%s %s\n'  "$C_PURPLE" "$ts" "$C_RST" "$C_GREY"  "$C_RST" "$name" ;;
  esac
}
# Everything printed below the checklist block is "tail": lines an interactive
# prompt or an error printed while a task ran. _TAIL counts them so the animator
# can find its way back to the block with relative moves only. There is
# deliberately NO DECSC/DECRC (`\033[s`/`\033[u`): some terminals honour it and
# some ignore it, and where it is ignored the old relative-move version walked
# down the screen (2026-10-16, "repository management goes wild").
# Print one console line below the block, counting it while a task is running.
_note() {
  printf '%s\n' "$*"
  [ -n "$TASK_ACTIVE" ] && [ -n "$TASK_DRAWN" ] && _TAIL=$(( ${_TAIL:-0} + 1 ))
  return 0
}
# Count lines printed by something other than _note (a read prompt's own line).
_task_count() { [ -n "$TASK_ACTIVE" ] && [ -n "$TASK_DRAWN" ] && _TAIL=$(( ${_TAIL:-0} + ${1:-1} )); return 0; }
# Fancy status lines below the checklist.
_warn_note() { _note "$(printf '  %s[WARN]%s  %s' "$C_ORANGE" "$C_RST" "$*")"; }
_err_note()  { _note "$(printf '  %s[ERROR]%s %s' "$C_RED" "$C_RST" "$*")"; }
# A colored titled section rule (used to frame the post-install error/warn blocks).
_section() { _note ""; _note "$(printf '%s── %s ──────────────────────────────────%s' "$2" "$1" "$C_RST")"; }
# Redraw row $1 in place: stand on the last block row (stepping over the tail),
# step up to the row, rewrite, step back to the tail bottom.
#
# Emitted as ONE printf (one write to the tty): the whole move-up + row +
# move-back travels as a single frame, so the terminal never paints an
# intermediate state (2026-10-16: separate writes flushed the erase before the
# rewrite, flickering the row ~10x/s). There is deliberately no `\033[K`: every
# state of a row is exactly the same width (the status field is always 8 wide —
# an HH:MM:SS ts or the 8-cell anim field), so the new row overwrites the old
# in place and clearing the line — the other half of the flicker — is
# unnecessary. Zero-count moves (`\033[0A`, treated as 1 by some terminals) are
# never emitted.
_task_update() {
  { [ -n "$TASK_DRAWN" ] && [ -t 1 ]; } || return 0
  local i="$1" t="${_TAIL:-0}"
  local d=$(( TASK_TOTAL - i ))
  local up=$(( t + d )) back=$(( d - 1 + t ))
  local mup="" mback="" row
  [ "$up"   -gt 0 ] && mup=$'\033['"$up"$'A'
  [ "$back" -gt 0 ] && mback=$'\033['"$back"$'B'
  row=$(_task_row "$i")
  printf '%s%s\n%s' "$mup" "$row" "$mback" >/dev/tty
}
# Background animator for the running row (TTY only).
_task_anim() {
  local i="$1" pos=0
  while :; do pos=$(( (pos + 1) % 14 )); ANIM_POS=$pos; _task_update "$i"; sleep 0.1; done
}
# Stop the animator while an interactive prompt owns the tty, so it cannot redraw
# over the prompt. Ref-counted so nested prompts work.
_task_pause() {
  _ANIM_PAUSE=$(( ${_ANIM_PAUSE:-0} + 1 ))
  [ "$_ANIM_PAUSE" -gt 1 ] && return 0
  [ -n "$ANIM_PID" ] && { kill "$ANIM_PID" 2>/dev/null; wait "$ANIM_PID" 2>/dev/null; ANIM_PID=; }
}
# Wipe the tail (the prompt/output printed below the block), redraw the running
# row, and restart the animator — so a prompt's app list/prompt vanishes and the
# checklist resumes on its own row instead of a duplicate being appended after it.
_task_resume() {
  _ANIM_PAUSE=$(( ${_ANIM_PAUSE:-1} - 1 )); [ "$_ANIM_PAUSE" -lt 0 ] && _ANIM_PAUSE=0
  [ "$_ANIM_PAUSE" -gt 0 ] && return 0
  if [ -n "$TASK_DRAWN" ] && [ -n "$TASK_ACTIVE" ] && [ -t 1 ]; then
    [ "${_TAIL:-0}" -gt 0 ] && printf '\033[%dA\033[J' "${_TAIL}" >/dev/tty
    _TAIL=0
    _task_update "$TASK_CUR"
  fi
  [ -n "$TASK_DRAWN" ] && [ -n "$TASK_ACTIVE" ] && [ -z "$ANIM_PID" ] && {
    _task_anim "$TASK_CUR" & ANIM_PID=$!
  }
}
_tasks_draw() {
  local i
  for i in $(seq 0 $((TASK_TOTAL - 1))); do TASK_STATE[$i]=wait; TASK_TS[$i]=$(date +%H:%M:%S); done
  [ -t 1 ] || return 0
  for i in $(seq 0 $((TASK_TOTAL - 1))); do _task_row "$i"; done
  _TAIL=0
  TASK_DRAWN=1
}
task_start() {
  TASK_CUR=$(( TASK_CUR + 1 )); TASK_ACTIVE=1 TASK_ERR=
  TASK_STATE[$TASK_CUR]=run
  if [ -n "$TASK_DRAWN" ]; then
    _task_update "$TASK_CUR"
    _task_anim "$TASK_CUR" & ANIM_PID=$!
  fi
}
task_end() {
  [ -n "$TASK_ACTIVE" ] || return 0
  [ -n "$ANIM_PID" ] && { kill "$ANIM_PID" 2>/dev/null; wait "$ANIM_PID" 2>/dev/null; ANIM_PID=; }
  TASK_TS[$TASK_CUR]=$(date +%H:%M:%S)
  [ -n "${TASK_ERR:-}" ] && TASK_STATE[$TASK_CUR]=error || TASK_STATE[$TASK_CUR]=done
  if [ -n "$TASK_DRAWN" ]; then _task_update "$TASK_CUR"; else _task_row "$TASK_CUR"; fi
  TASK_ACTIVE= TASK_ERR=
}

# ───────────────────── fresh log for this run ──────────────────────────────
# install.log describes ONE run: truncate it the moment the run starts, then
# announce what the run is. Called from main() before any prompt, so even an
# aborted run leaves a log that says so.
init_log() {
  install -d -m 0755 "$LOG_DIR"
  : >"$LOG"
  chmod 600 "$LOG"
  log "=== install.sh run $(date -Is) — node ${NODE_NAME:-?} repo $REPO"
  log "=== args: $*"
}

