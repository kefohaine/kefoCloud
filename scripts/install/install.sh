# Vaultwarden SMTP sender mailbox (vaultwarden@$DOMAIN) — created after the
# mailserver container is up (called after containers_up). The SMTP vars the
# vaultwarden container uses come from modules/vaultwarden/.env (written by
# seed_stack); this step only makes the mailbox exist so auth succeeds.
vaultwarden_setup() {
  cd "$REPO" || exit 1
  # The vaultwarden SMTP sender mailbox depends on the mail module: with mail
  # disabled there is no mailserver to authenticate against, so skip it.
  if ! mod_on mail; then
    log "  mail module disabled — skipping mailbox vaultwarden@$DOMAIN"
    return 0
  fi
  . modules/vaultwarden/.env
  # ${SMTP_PASSWORD:-}: an unbound expansion here used to kill this function's
  # pipeline subshell, so the only visible symptom was "mailbox not created"
  # instead of the real fault (seed_stack had skipped writing the key). Name
  # it explicitly now (2026-09-25).
  if [ -z "${SMTP_PASSWORD:-}" ]; then
    fail vaultwarden_setup "SMTP_PASSWORD missing from modules/vaultwarden/.env"
    return
  fi
  mailbox_add "vaultwarden@$DOMAIN" "$SMTP_PASSWORD" \
    || fail vaultwarden_setup "mailbox vaultwarden@$DOMAIN not created"
}

# Create the default Vaultwarden account (the one the success block prints).
# Vaultwarden has no user CLI, so — like Uptime Kuma — the account is written
# into its SQLite DB by scripts/modules/vaultwarden-user.sh (Bitwarden's client
# crypto: master-key hash, the encrypted user key and an RSA key pair). This
# step only runs once the container has made the DB + schema; a re-run leaves an
# existing account untouched (never resets it), so an operator's vault survives.
vaultwarden_admin() {
  cd "$REPO" || exit 1
  . modules/vaultwarden/.env
  if [ -z "${VAULTWARDEN_ADMIN_USER:-}" ] || [ -z "${VAULTWARDEN_ADMIN_PASSWORD:-}" ]; then
    fail vaultwarden_admin "VAULTWARDEN_ADMIN_* missing from modules/vaultwarden/.env"
    return
  fi
  # The container creates db.sqlite3 (and the users table) on first boot — poll
  # for both, not just the file (an empty file is not a usable schema).
  local i=0
  while [ $i -lt 150 ]; do
    bash scripts/modules/vaultwarden-user.sh list >/dev/null 2>&1 && break
    sleep 2; i=$((i+2))
  done
  if ! bash scripts/modules/vaultwarden-user.sh list >/dev/null 2>&1; then
    fail vaultwarden_admin "vault db has no users schema after 5 min"
    return
  fi
  bash scripts/modules/vaultwarden-user.sh ensure "$VAULTWARDEN_ADMIN_USER" "$VAULTWARDEN_ADMIN_PASSWORD" \
    >>"$LOG" 2>&1 || fail vaultwarden_admin
}

# Publish the mailserver's DKIM key as a TXT record via the Cloudflare API —
# the whole mail-authentication stack (SPF/DKIM/DMARC + PTR) then only needs
# the operator's provider-side PTR. Runs after the mailserver is up
# (containers_up); requires ENABLE_OPENDKIM=0 in the mailserver compose
# (Rspamd signs — otherwise `setup config dkim` aborts on the conflict).
dkim_setup() {
  cd "$REPO" || exit 1
  local rec value zone id i=0
  # The mailserver restart-loops until Caddy has written its mail.$DOMAIN cert
  # (SSL_TYPE=manual) — wait for a live container, or `setup config dkim`
  # aborts and the error surfaces as a bare "keygen".
  while [ $i -lt 90 ]; do
    docker exec mailserver true >/dev/null 2>&1 && break
    sleep 2; i=$((i+2))
  done
  # rc=1 when the key already exists ("Not overwriting existing files") — the
  # idempotent case, so judge by the public key, not the exit code.
  docker exec mailserver setup config dkim domain "$DOMAIN" >/dev/null 2>&1 || true
  # *.public.txt is the BIND zone-file form and splits the key across quoted
  # lines (grepping it published a truncated key); *.public.dns.txt is the
  # single-line record, ready to publish.
  rec=$(docker exec mailserver sh -c 'cat /tmp/docker-mailserver/rspamd/dkim/*.public.dns.txt' 2>/dev/null \
    | grep -oE 'p=[A-Za-z0-9+/=]+' | sed 's/p=//' | tr -d '\n')
  [ -n "$rec" ] || fail dkim_setup "no public key"
  value="v=DKIM1; k=rsa; p=$rec"
  zone=$(curl -s -H "Authorization: Bearer $CF_API_TOKEN" "https://api.cloudflare.com/client/v4/zones?name=$DOMAIN" \
    | python3 -c "import sys,json; d=json.load(sys.stdin); print(d['result'][0]['id'] if d.get('result') else '')" 2>/dev/null)
  [ -n "$zone" ] || fail dkim_setup "zone lookup"
  # drop any stale mail._domainkey TXT records, then publish ours
  for id in $(curl -s -H "Authorization: Bearer $CF_API_TOKEN" \
      "https://api.cloudflare.com/client/v4/zones/$zone/dns_records?type=TXT&name=mail._domainkey.$DOMAIN" \
      | python3 -c "import sys,json; [print(r['id']) for r in (json.load(sys.stdin).get('result') or [])]" 2>/dev/null); do
    curl -s -X DELETE -H "Authorization: Bearer $CF_API_TOKEN" \
      "https://api.cloudflare.com/client/v4/zones/$zone/dns_records/$id" >/dev/null
  done
  python3 - "$CF_API_TOKEN" "$zone" "$value" <<'EOF' || fail dkim_setup "record publish"
import sys, json, urllib.request
tok, zone, val = sys.argv[1], sys.argv[2], sys.argv[3]
req = urllib.request.Request(f"https://api.cloudflare.com/client/v4/zones/{zone}/dns_records",
  data=json.dumps({"type": "TXT", "name": "mail._domainkey", "content": val, "ttl": 1, "proxied": False}).encode(),
  headers={"Authorization": "Bearer " + tok, "Content-Type": "application/json"}, method="POST")
sys.exit(0 if json.loads(urllib.request.urlopen(req).read().decode()).get("success") else 1)
EOF
  detail "DKIM published: mail._domainkey TXT for $DOMAIN (PTR remains provider-side)"
}

ssl_mode_full() {
  # API first (needs Zone Settings read on the token); fall back to a
  # behavior probe — Flexible/Off makes CF reach the origin over HTTP and
  # Caddy answers a 308 back to the same https URL (redirect loop).
  local mode hdrs code loc
  mode=$(curl -s -H "Authorization: Bearer $CF_API_TOKEN" \
    "https://api.cloudflare.com/client/v4/zones/$ZONE_ID/settings/ssl" 2>/dev/null \
    | jq -r '.result.value // empty' 2>/dev/null)
  case "$mode" in full|strict) return 0 ;; esac
  [ -n "$mode" ] && return 1
  hdrs=$(curl -sI --max-time 15 "https://cloud.$DOMAIN" 2>/dev/null | tr -d '\r')
  code=$(echo "$hdrs" | awk 'NR==1{print $2}')
  loc=$(echo "$hdrs" | awk 'tolower($1)=="location:"{print $2; exit}')
  [ "$code" = "308" ] && [[ "$loc" == *"cloud.$DOMAIN"* ]] && return 1
  return 0
}

cf_mail_record() { # $1=type(TXT/MX) $2=relative name (or apex) $3=content $4=priority(MX only)
  local type="$1" name="$2" content="$3" prio="${4:-0}" fqdn="$2" records rid current payload response
  [ "$name" = "$DOMAIN" ] || fqdn="$name.$DOMAIN"
  records=$(curl -fsS -G -H "Authorization: Bearer $CF_API_TOKEN" \
    --data-urlencode "type=$type" --data-urlencode "name=$fqdn" \
    "https://api.cloudflare.com/client/v4/zones/$ZONE_ID/dns_records") || {
    fail dns_mail_txt "Cloudflare $type lookup failed for $fqdn"; return 1;
  }
  rid=$(printf '%s' "$records" | jq -r '.result[0].id // empty')
  current=$(printf '%s' "$records" | jq -r '.result[0].content // empty')
  [ -n "$rid" ] && [ "$current" = "$content" ] && return 0
  payload=$(jq -nc --arg content "$content" --arg name "$fqdn" --arg type "$type" --argjson prio "$prio" \
    '{type:$type,name:$name,content:$content,ttl:1} + (if $type == "MX" then {priority:$prio} else {} end)')
  if [ -n "$rid" ]; then
    response=$(curl -fsS -X PUT -H "Authorization: Bearer $CF_API_TOKEN" \
      -H "Content-Type: application/json" \
      "https://api.cloudflare.com/client/v4/zones/$ZONE_ID/dns_records/$rid" -d "$payload") || {
      fail dns_mail_txt "Cloudflare $type update failed for $fqdn"; return 1;
    }
  else
    response=$(curl -fsS -X POST -H "Authorization: Bearer $CF_API_TOKEN" \
      -H "Content-Type: application/json" \
      "https://api.cloudflare.com/client/v4/zones/$ZONE_ID/dns_records" -d "$payload") || {
      fail dns_mail_txt "Cloudflare $type create failed for $fqdn"; return 1;
    }
  fi
  if [ "$(printf '%s' "$response" | jq -r '.success // false')" != "true" ]; then
    fail dns_mail_txt "Cloudflare $type publish failed for $fqdn"
    return 1
  fi
  detail "  $type record ensured: $fqdn"
  return 0
}
# Only the records the mail module needs: the MX that receives inbound mail
# (pointing at the mail vhost — Postfix's virtual_mailbox_domains accepts $DOMAIN
# there) and the SPF policy that authorizes the Docker Mailserver host to send.
# TTL 1 is Cloudflare's "Auto". Both are idempotent: a record already carrying
# the wanted content is left untouched, so a re-check never rewrites the zone.
cf_mail_dns() {
  local mx="mail.$DOMAIN" spf cur
  # SPF must list the sending host. v=spf1 -all (all senders rejected) is the
  # "domain sends no mail" policy and would fail every inbound spam check on our
  # own outbound, so only -all is left alone (an operator's deliberate choice);
  # anything else (stub, an old policy) is replaced by the a:mx policy.
  cur=$(curl -fsS -G -H "Authorization: Bearer $CF_API_TOKEN" \
    --data-urlencode "type=TXT" --data-urlencode "name=$DOMAIN" \
    "https://api.cloudflare.com/client/v4/zones/$ZONE_ID/dns_records" 2>/dev/null \
    | jq -r '[.result[]?.content // empty] | map(select(startswith("v=spf1"))) | first // empty' 2>/dev/null)
  spf="v=spf1 a:$mx mx -all"
  case "$cur" in
    "$spf"|"v=spf1 -all") ;;
    *) cf_mail_record TXT "$DOMAIN" "$spf" ;;
  esac
  cf_mail_record MX "$DOMAIN" "$mx" 10
  # DKIM placeholder: a wildcard TXT so selectors exist before Rspamd signs
  # (dkim_setup publishes the real mail._domainkey record right after).
  cf_mail_record TXT '*._domainkey' 'v=DKIM1; p='
  cf_mail_record TXT '_dmarc' 'v=DMARC1; p=reject; sp=reject; adkim=s; aspf=s;'
  # SPF/DKIM/DMARC still can't authorize a relay by themselves without a
  # published PTR, but only the provider can create it — reported in the
  # success block's additional steps.
  return 0
}

  cf_dns() {
  HOST_IP=$(curl -s4 ifconfig.me)
  ZONE_ID=$(curl -s -H "Authorization: Bearer $CF_API_TOKEN" \
    "https://api.cloudflare.com/client/v4/zones?name=$DOMAIN" | jq -r '.result[0].id // empty')
  if [ -z "$ZONE_ID" ]; then
    fail zone
    return
  fi
  cf_record() { # $1=host $2=proxied(true/false)
    local rid
    rid=$(curl -s -H "Authorization: Bearer $CF_API_TOKEN" \
      "https://api.cloudflare.com/client/v4/zones/$ZONE_ID/dns_records?type=A&name=$1.$DOMAIN" | jq -r '.result[0].id // empty')
    if [ -z "$rid" ]; then
      curl -s -X POST -H "Authorization: Bearer $CF_API_TOKEN" -H "Content-Type: application/json" \
        "https://api.cloudflare.com/client/v4/zones/$ZONE_ID/dns_records" \
        -d "{\"type\":\"A\",\"name\":\"$1.$DOMAIN\",\"content\":\"$HOST_IP\",\"ttl\":1,\"proxied\":$2}" \
        >>"$LOG" 2>&1 || fail "dns_$1"
    fi
  }
  # proxied (orange cloud): vault/kuma/www. talk rides on the cloud door.
  for h in cloud vault kuma www; do
    case "$h" in
      cloud) mod_on cloud && cf_record "$h" false;;
      vault) mod_on vault && cf_record "$h" true;;
      kuma)  mod_on monitor && cf_record "$h" true;;
      www)   cf_record "$h" true;;
    esac
  done
  # talk/mail MUST be DNS-only (grey cloud): TURN relays media over
  # UDP/TCP 3478/5349 + 49160-49200 and SMTP/IMAP also bypass the CF proxy
  # (HTTP(S) only). Caddy still gets their LE certs via DNS-01.
  mod_on cloud && cf_record talk false
  mod_on mail  && cf_record mail false
  mod_on mail && cf_mail_dns
  curl -s -X PATCH -H "Authorization: Bearer $CF_API_TOKEN" -H "Content-Type: application/json" \
    "https://api.cloudflare.com/client/v4/zones/$ZONE_ID/settings/ssl" -d '{"value":"full"}' >>"$LOG" 2>&1 || true
  # DNS-only tokens can't set SSL mode; surface it as an expected manual step.
  if ! ssl_mode_full; then
    fail sslmode
  fi
}

# Issuer of the cert Caddy presents for one vhost, polled while ACME finishes.
cert_issuer() {
  local h="$1" i=0 iss=""
  while [ $i -lt 45 ]; do
    iss=$(echo | timeout 10 openssl s_client -connect 127.0.0.1:443 -servername "$h.$DOMAIN" 2>/dev/null \
      | openssl x509 -noout -issuer 2>/dev/null | cut -d'=' -f2-)
    case "$iss" in *"Let's Encrypt"*) break;; esac
    i=$((i+2)); sleep 2
  done
  echo "$iss"
}

issue_certs() {
  local hosts="" h iss pending=()
  hosts="www"
  mod_on cloud   && hosts="$hosts cloud talk"
  mod_on vault   && hosts="$hosts vault"
  mod_on monitor && hosts="$hosts kuma"
  mod_on mail    && hosts="$hosts mail"
  for h in $hosts; do
    curl -sk --resolve "$h.$DOMAIN:443:127.0.0.1" -o /dev/null "https://$h.$DOMAIN/" >>"$LOG" 2>&1 || true
    sleep 3
  done
  # The trigger requests above only wake Caddy up — the first DNS-01 issuance
  # is not instant, so cert_issuer polls before declaring failure. The two
  # outcomes are NOT the same and must not be treated as one:
  #   * empty issuer  = Caddy has not finished issuing yet (normal warm-up);
  #                     wait it out, never restart the edge for it.
  #   * real issuer that is not Let's Encrypt = an order genuinely stuck, which
  #     one restart re-attempts (observed on kuma.$DOMAIN: every other vhost
  #     issued while that lock kept retrying).
  # Restarting on the empty case alone killed every live connection for nothing.
  local stuck=() h2
  for h in $hosts; do
    iss=$(cert_issuer "$h")
    case "$iss" in
      *"Let's Encrypt"*) ;;
      "") pending+=("$h") ;;
      *) stuck+=("$h") ;;
    esac
  done
  if [ ${#pending[@]} -gt 0 ]; then
    detail "  ${#pending[@]} cert(s) still issuing (${pending[*]}) — waiting for Caddy to finish"
    for h2 in "${pending[@]}"; do
      case "$(cert_issuer "$h2")" in *"Let's Encrypt"*) ;; *) stuck+=("$h2");; esac
    done
  fi
  if [ ${#stuck[@]} -gt 0 ]; then
    detail "  ${#stuck[@]} cert order(s) stuck (${stuck[*]}) — restarting Caddy to re-attempt"
    # The container is named `caddy` (compose container_name), not $DOMAIN —
    # restarting "$DOMAIN" always failed with "No such container" and the
    # re-attempt never happened (2026-09-25).
    docker restart caddy >>"$LOG" 2>&1 || true
    sleep 5
  fi
  for h in $hosts; do
    iss=$(cert_issuer "$h")
    case "$iss" in
      *"Let's Encrypt"*) ;;
      *) fail "cert_$h" "issuer was: $iss";;
    esac
  done
}

# Old-project references must not survive in anything the installer deploys
# (compose files, host config, Makefile, recipes). docs/ and scripts/ are out
# of scope by design: docs record the rename as history, and the scripts
# (this installer, the rewrite/import tooling) name the old project by nature
# — counting them made the check unsatisfiable on the repo's own tree.
sweep_hits() {
  # Flag only legacy placeholders that cannot legitimately remain after a
  # rename (the skeleton shipped "exampleuser" as owner and "homelab" as project).
  # Scoped to the two dirs that can actually carry a placeholder: the tracked
  # modules/ and config/ trees. Scanning $REPO root-wide walked data/ (the live
  # instance: maildirs, pgdata, certs — hundreds of thousands of files, ~23 s per
  # pass) and had to be filtered back out afterwards; `-not -path` was a FIND flag
  # handed to grep, so it did nothing and the exclusion rested on the kefoCloud
  # grep alone. docs/ and scripts/ are out of scope by design: docs record the
  # rename as history and these scripts name the old project by nature.
  grep -rlI -e homelab -e exampleuser \
    "$REPO/modules" "$REPO/config" \
    --exclude-dir=.git --exclude-dir=archives \
    --exclude='*.md' --exclude='.env' 2>/dev/null |
    grep -v 'kefoCloud' || true
}

sweep() {
  [ -z "$(sweep_hits)" ] || fail sweep
}

