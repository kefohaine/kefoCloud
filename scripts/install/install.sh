load_state() {
  [ -f "$INSTALL_STATE" ] && . "$INSTALL_STATE"
  local uniq=() t
  for t in "${ERR_TAGS[@]:-}"; do
    [[ " ${uniq[*]:-} " == *" $t "* ]] || uniq+=("$t")
  done
  ERR_TAGS=("${uniq[@]}")
}

# Is a module enabled for THIS run? One definition, one fallback. The fallback
# is "enabled" because a resume or a fresh run always sets MOD_* from the
# prompts — an UNSET value can only mean "this run never asked", which is a
# run that should be doing the full job, not silently skipping steps. Every
# caller goes through here, so a step can never disagree with the module record
# written to install.state (2026-10-15: three different call sites disagreed on
# the fallback, and one of them made a healthy Nextcloud report a failure).
mod_on() {
  # Build the name first, then indirect it: `${MOD_${1^^}:-true}` is NOT valid
  # bash (nested expansion inside a variable name) — it errors and every test
  # silently becomes false, which is exactly the bug that once recorded an empty
  # module set and muted smoke (2026-10-04).
  local name="MOD_${1^^}"
  [ "${!name:-true}" = "true" ]
}

# The enabled set as recorded in state: the modules the operator chose. Built
# from the MOD_* answers; an unset MOD_* is NEVER assumed true here (unlike the
# install path, which defaults to true) — the record only names answered ones.
enabled_modules_list() {
  local k v out=""
  for k in cloud vault mail monitor; do
    v="MOD_${k^^}"
    [ "${!v:-}" = "true" ] && out+="$k "
  done
  printf '%s' "${out% }"
}

# install.sh is the SOLE writer of $INSTALL_STATE — including `finished`.
# Everything else (make smoke, make fetch, modules.sh) only reads it.
# A module record exists only for a FINISHED install: while finished is not yet
# true the enabled_modules field is written empty, so a half-answered run can
# never look installed.
save_state() {
  umask 077
  install -d -m 0700 "$(dirname "$INSTALL_STATE")"
  local tmp="$INSTALL_STATE.tmp.$$" em=""
  [ "${FINISHED:-false}" = "true" ] && em="$(enabled_modules_list)"
  # Every value is written with `printf %q`, never inside literal quotes: the
  # file is later `source`d by load_state, so a value containing a quote or a
  # `$(…)` must be escaped, not interpolated raw (a free-form commit name could
  # otherwise inject on the next run).
  {
    printf 'DOMAIN=%q\n'             "${DOMAIN:-}"
    printf 'CF_API_TOKEN=%q\n'       "${CF_API_TOKEN:-}"
    printf 'TS_AUTHKEY=%q\n'         "${TS_AUTHKEY:-}"
    printf 'TS_IP=%q\n'              "${TS_IP:-}"
    # The raw module ANSWERS, so a resume reuses the choice (empty once a module
    # has not been asked yet — ask_modules re-asks only the empty ones).
    printf 'MOD_CLOUD=%q\n'          "${MOD_CLOUD:-}"
    printf 'MOD_VAULT=%q\n'          "${MOD_VAULT:-}"
    printf 'MOD_MAIL=%q\n'           "${MOD_MAIL:-}"
    printf 'MOD_MONITOR=%q\n'        "${MOD_MONITOR:-}"
    # The RECORD (for other scripts) — only real once the install is finished.
    printf 'enabled_modules=%q\n'    "$em"
    printf 'finished=%q\n'           "${FINISHED:-false}"
    printf 'GH_REMOTE=%q\n'          "${GH_REMOTE:-false}"
    printf 'GH_AUTH_OK=%q\n'         "${GH_AUTH_OK:-0}"
    printf 'GITHUB_COMMIT_NAME=%q\n' "${GITHUB_COMMIT_NAME:-}"
    printf 'GITHUB_COMMIT_EMAIL=%q\n' "${GITHUB_COMMIT_EMAIL:-}"
    printf 'ERR_TAGS=(%s)\n'         "$(printf '%q ' "${ERR_TAGS[@]}")"
  } > "$tmp"
  chmod 600 "$tmp"
  mv -f "$tmp" "$INSTALL_STATE" 2>/dev/null || sudo mv -f "$tmp" "$INSTALL_STATE" || rm -f "$tmp"
  chown root:root "$INSTALL_STATE" 2>/dev/null || true
}

# One-time import of a legacy installer state (/var/lib/<GITHUB_USER>/setup.state,
# or the pre-$GITHUB_USER /var/lib/<host>. setup.state). Only moves the file: the
# legacy MOD_* keys are not read back, so module answers are re-asked once.
migrate_state() {
  [ -f "$INSTALL_STATE" ] && return 0
  local old cands=()
  [ -n "${GITHUB_USER:-}" ] && cands+=("/var/lib/$GITHUB_USER/setup.state")
  [ -n "${NODE_NAME:-}" ]   && cands+=("/var/lib/$NODE_NAME/setup.state")
  for old in "${cands[@]}"; do
    [ -f "$old" ] || continue
    install -d -m 0700 "$(dirname "$INSTALL_STATE")"
    mv -f "$old" "$INSTALL_STATE" 2>/dev/null || continue
    chmod 600 "$INSTALL_STATE"
    detail "  migrated legacy installer state: $old -> $INSTALL_STATE"
    return 0
  done
}

# $LOG lives outside the repo and must exist before ANYTHING redirects into it
# (a `>>"$LOG"` whose directory is missing fails the redirection, the command
# behind it is never run, and `|| fail ...` then reports the step as broken) —
# and before the first `log()`, or tee swallows that line. $DATA (install.state)
# is tightened to 0700 because it holds the CF token + Tailscale key. Idempotent;
# main() calls it first thing.
ensure_runtime_dirs() {
  install -d -m 0755 "$LOG_DIR"
  install -d -m 0700 "$DATA"
}

# Module prompts are ALWAYS asked — there is no answer-sheet defaults file, and
# every prompt is asked on every run except when a resume supplies the answer.
# Yes/no affirmation: ONLY the literal words yes / no are accepted — no
# y/n/Enter shorthand, no default (a typo is re-asked). The answer is RECORDED
# as the boolean true / false in the named variable, never as what was typed.
ask_boolean() {   # ask_boolean <question> <variable>
  _task_pause
  _ask_boolean_raw "$@"
  local rc=$?
  _task_resume
  return $rc
}
_ask_boolean_raw() {
  local q="$1" var="$2" answer
  while :; do
    printf '%s[INFO]%s %s (yes/no): ' "$C_GREY" "$C_RST" "$q"
    read -r answer || { _task_count 1; return 1; }
    _task_count 1
    case "${answer,,}" in
      yes) printf -v "$var" '%s' true;  return 0 ;;
      no)  printf -v "$var" '%s' false; return 0 ;;
      *)   echo "   type yes or no."; _task_count 1 ;;
    esac
  done
}

# ONE prompt for the whole module set, space-separated (multiple spaces / commas
# tolerated, any order). Every name not listed becomes false. On a resume, when
# all four answers are already saved, the prompt is skipped.
ask_modules() {
  local k name all=1 ans ok
  for k in cloud vault mail monitor; do
    name="MOD_${k^^}"; [ -n "${!name:-}" ] || all=
  done
  [ -n "$all" ] && return 0
  while :; do
    printf '%s[INFO]%s Modules to install, separated by spaces (cloud mail vault monitor): ' \
      "$C_GREY" "$C_RST"
    read -r ans || exit 1
    ans="${ans,,}"; ans="${ans//,/ }"
    ok=1
    for k in $ans; do
      case "$k" in cloud|vault|mail|monitor) ;; *) echo "   unknown module: $k"; ok= ;; esac
    done
    [ -n "$ok" ] || continue
    for k in cloud vault mail monitor; do
      name="MOD_${k^^}"
      case " $ans " in *" $k "*) printf -v "$name" '%s' true ;; *) printf -v "$name" '%s' false ;; esac
    done
    return 0
  done
}

# ── SSH access: STRICT and required ──────────────────────────────────────
# The box ends up root-key-only with password auth off, so a usable pubkey from
# a device the operator actually holds is REQUIRED — the installer asks for it
# here instead of leaving it as a follow-up `ssh_keys` step. Only the PUBLIC
# half is pasted; the private half never leaves that device. Nothing is ever
# minted server-side (that is the difference to the opt-in GitHub key below).
ask_ssh_key() {
  local line info
  mkdir -p /root/.ssh && chmod 700 /root/.ssh
  if [ -s /root/.ssh/authorized_keys ] && grep -q . /root/.ssh/authorized_keys; then
    detail "  SSH: $(grep -c . /root/.ssh/authorized_keys) key(s) already authorized — paste skipped"
    return 0
  fi
  printf '\n SSH is key-only (root, no password). On the device you will connect FROM run\n'
  printf '   cat ~/.ssh/id_ed25519.pub\n'
  printf ' and paste that one line here (no ssh-copy-id needs to run yet). Only the\n'
  printf ' PUBLIC half goes to the server; the private half never leaves your device.\n'
  printf ' Use a key you can actually use — hardening is key-only, so a wrong or lost\n'
  printf ' key is a lockout.\n\n'
  while :; do
    read -rp "Public SSH key of your device: " line \
      || { echo "A public key is required — re-run the installer from a terminal."; exit 1; }
    line="$(printf '%s' "$line" | tr -d '\r' | sed 's/^[[:space:]]*//; s/[[:space:]]*$//')"
    case "$line" in
      "") continue ;;
      *"PRIVATE KEY"*) echo "   that is the PRIVATE key — never paste it; paste the .pub line."; continue ;;
    esac
    info="$(printf '%s\n' "$line" | ssh-keygen -lf - 2>/dev/null)"
    [ -n "$info" ] || { echo "   not a valid public key — paste the whole .pub line (ssh-ed25519 AAAA… you@device)."; continue; }
    grep -qxF "$line" /root/.ssh/authorized_keys 2>/dev/null \
      || printf '%s\n' "$line" >> /root/.ssh/authorized_keys
    chmod 600 /root/.ssh/authorized_keys
    detail "  SSH key accepted: $info"
    return 0
  done
}

# 2 — GitHub remote-access opt-in with its sub-prompts. The sub-prompts appear
# ONLY when the opt-in is yes; the minted key's authorization is verified
# automatically by github_access (no manual "press Enter to re-check" step).
# Whether the authenticated account may actually PUSH to this repo is not
# checked here — the push itself is the check (GitHub rejects a non-collaborator).
github_cred_inputs() {
  # Asked on EVERY run until the key is actually authorized (GH_AUTH_OK=1) or a
  # push has succeeded — an unanswered/unauthorized GitHub step must not be
  # silently skipped just because a previous run recorded GH_REMOTE=false. Once
  # authorized (or pushed) the answer is trusted and the prompt is gone.
  if [ "${GH_REMOTE:-}" = "true" ] && [ "${GH_AUTH_OK:-0}" != "1" ] \
     && [ -s "$GH_KEY" ] && github_auth_ok; then
    GH_AUTH_OK=1
    save_state
  fi
  if [ "${GH_AUTH_OK:-0}" != "1" ]; then
    unset GH_REMOTE
    ask_boolean "Are you a collaborator of $REPO_NAME?" GH_REMOTE || exit 1
  fi
  save_state
  [ "${GH_REMOTE}" = "true" ] || return 0
  # One prompt for both halves of the commit identity: "name email". REQUIRED
  # when pushing is on — there is no blank-skip and no root fallback.
  if [ -z "${GITHUB_COMMIT_NAME:-}" ] || [ -z "${GITHUB_COMMIT_EMAIL:-}" ]; then
    local line
    while :; do
      printf '%s[INFO]%s GitHub commit identity, separated by spaces (name email): ' "$C_GREY" "$C_RST"
      read -r line \
        || { echo "A commit identity is required when pushing is enabled."; exit 1; }
      line="$(printf '%s' "$line" | tr -d '\r' | sed 's/^[[:space:]]*//; s/[[:space:]]*$//')"
      # The email is the LAST token, the name is everything before it — so a
      # multi-word name survives intact.
      if [[ "$line" == *" "* ]] && [ -n "${line% *}" ] && [ -n "${line##* }" ]; then
        GITHUB_COMMIT_NAME="${line% *}"
        GITHUB_COMMIT_EMAIL="${line##* }"
        break
      fi
      echo "   enter both a name and an email — e.g. Jane Doe jane@example.com"
    done
  fi
  save_state
  github_access
}

ask_inputs() {
  # Inputs are collected in ONE fixed order, all before any install work, and
  # each is persisted immediately (save_state) so an abort mid-run leaves the
  # answers for a resume. Order: github-remote-access (+ identity), device-ssh,
  # tailscale, cloudflare, domain, modules. The resume question precedes all of
  # these (it decides whether saved answers are reused).

  # 2 — GitHub remote access: opt-in, then identity + key authorization.
  github_cred_inputs

  # 3 — device SSH public key (strict, required).
  ask_ssh_key

  # 4 — Tailscale auth key (input hidden).
  if [ -z "${TS_AUTHKEY:-}" ]; then
    printf '%s[INFO]%s Tailscale Authentication Key: ' "$C_GREY" "$C_RST"
    read -rsp "" TS_AUTHKEY; echo
  fi
  [ -n "$TS_AUTHKEY" ] || { echo "Auth key required."; exit 1; }
  save_state

  # 5 — Cloudflare API token (input hidden).
  if [ -z "${CF_API_TOKEN:-}" ]; then
    printf '%s[INFO]%s Cloudflare API Token: ' "$C_GREY" "$C_RST"
    read -rsp "" CF_API_TOKEN; echo
  fi
  [ -n "$CF_API_TOKEN" ] || { echo "Token required."; exit 1; }
  save_state

  # 6 — domain.
  if [ -z "${DOMAIN:-}" ]; then
    printf '%s[INFO]%s Domain Name: ' "$C_GREY" "$C_RST"
    read -r DOMAIN
  fi
  DOMAIN="${DOMAIN,,}"
  [[ "$DOMAIN" =~ ^[a-zA-Z0-9.-]+\.[a-zA-Z]{2,}$ ]] || { echo "Invalid domain: $DOMAIN"; exit 1; }
  save_state

  # 7 — modules (one space-separated prompt).
  ask_modules
  save_state
}

# write_state records the install in $INSTALL_STATE (the enabled modules + the
# `finished` checkpoint) — the ONE artefact every reader uses. It ALSO writes a
# cross-checked detection report (independent probes) purely as evidence: a
# declared/confirmed mismatch is logged as a warning, never used as truth.
#   install.state                    enabled modules + finished + prompted values
#   installed-modules.detected.conf  modules confirmed by independent probes
#   installed-modules.report.txt     per-module, per-method evidence matrix
# Probes, deliberately independent of the record: (1) the container is running,
# (2) its compose file exists in the repo, (3) its data dir/db exists on disk,
# (4) its Caddy vhost exists. A module is "confirmed" when at least one fires.
write_state() {
  local det="$DATA/installed-modules.detected.conf"
  local rep="$DATA/installed-modules.report.txt"
  local m ct cf dd vh ev em

  save_state
  em="$(enabled_modules_list)"

  : > "$det"
  { echo "module detection report — $(date -Is)"
    echo "declared = install-time choice (MOD_*); probes are independent of it."
    echo; } > "$rep"

  for m in cloud vault mail monitor; do
    ct=0; cf=0; dd=0; vh=0
    case "$m" in
      cloud)   ct=$(docker ps --format '{{.Names}}' 2>/dev/null | grep -cx nextcloud)
               [ -f "$REPO/modules/nextcloud/docker-compose.yml" ] && cf=1
               [ -e "$DATA/cloud/users" ] && dd=1
               [ -f "$RENDER_DIR/caddy/vhosts/cloud.caddy" ] && vh=1 ;;
      vault)   ct=$(docker ps --format '{{.Names}}' 2>/dev/null | grep -cx vaultwarden)
               [ -f "$REPO/modules/vaultwarden/docker-compose.yml" ] && cf=1
               [ -e "$DATA/vault/data" ] && dd=1
               [ -f "$RENDER_DIR/caddy/vhosts/vault.caddy" ] && vh=1 ;;
      mail)    ct=$(docker ps --format '{{.Names}}' 2>/dev/null | grep -cxE 'mailserver|roundcube')
               [ -f "$REPO/modules/mailserver/docker-compose.yml" ] && cf=1
               [ -e "$DATA/mailserver/data" ] && dd=1
               [ -f "$RENDER_DIR/caddy/vhosts/mail.caddy" ] && vh=1 ;;
      monitor) ct=$(docker ps --format '{{.Names}}' 2>/dev/null | grep -cx uptimekuma)
               [ -f "$REPO/modules/uptimekuma/docker-compose.yml" ] && cf=1
               [ -e "$DATA/kuma/data" ] && dd=1
               [ -f "$RENDER_DIR/caddy/vhosts/kuma.caddy" ] && vh=1 ;;
    esac
    ev=$((ct+cf+dd+vh))
    [ "$ev" -gt 0 ] && echo "$m" >> "$det"
    printf '%-8s declared=%s running=%s compose=%s data=%s vhost=%s -> %s\n' \
      "$m" "$(mod_on "$m" && echo 1 || echo 0)" \
      "$ct" "$cf" "$dd" "$vh" "$([ "$ev" -gt 0 ] && echo PRESENT || echo absent)" >> "$rep"
  done

  detail "  wrote $INSTALL_STATE (enabled: ${em:-none}; finished=$FINISHED)"
  detail "  detected: $(paste -sd' ' "$det" || echo none) — evidence: $rep"
  if ! diff -q <(printf '%s\n' $em | sort) <(sort "$det") >/dev/null 2>&1; then
    log "  WARNING: declared modules != detected modules — see $rep"
  fi
}

# ───────────────── GitHub remote access (opt-in, last prompt) ─────────────

# The ONE keypair this installer mints: it has to exist on the box to push to
# the operator's repos. (The operator's own login key is never minted — it is
# pasted at the ask_ssh_key prompt.) The operator authorizes the printed PUBLIC
# key once.
GH_KEY=/root/.ssh/github_key

github_keygen() {
  [ -s "$GH_KEY" ] && return 0                      # never overwrite an existing key
  ssh-keygen -t ed25519 -N "" -C "$(id -un)@$(hostname -s) github_key" -f "$GH_KEY" >/dev/null 2>&1 || return 1
  chmod 600 "$GH_KEY"; chmod 644 "$GH_KEY.pub"
  # ssh does not offer this key by default: name it in the client config.
  grep -qs "IdentityFile $GH_KEY" /root/.ssh/config 2>/dev/null && return 0
  printf 'Host github.com\n  IdentityFile %s\n  IdentitiesOnly yes\n' "$GH_KEY" >> /root/.ssh/config
  chmod 600 /root/.ssh/config
}

# Pin github.com's host keys, but only ones whose fingerprint api.github.com
# publishes — a bare ssh-keyscan trusts whoever answered first.
github_known_hosts() {
  local scan fps published f n=0
  grep -qs 'github\.com' /root/.ssh/known_hosts 2>/dev/null && return 0
  scan="$(ssh-keyscan -t rsa,ecdsa,ed25519 github.com 2>/dev/null)" || return 0
  [ -n "$scan" ] || return 0
  fps="$(printf '%s\n' "$scan" | ssh-keygen -lf - 2>/dev/null | awk '{print $2}')"
  published="$(curl -fsS --max-time 10 https://api.github.com/meta 2>/dev/null \
    | python3 -c 'import json,sys; print("\n".join(json.load(sys.stdin)["ssh_key_fingerprints"].values()))' 2>/dev/null)"
  for f in $fps; do
    n=$((n+1))
    printf '%s\n' "$published" | grep -qxF "$f" || return 0   # unverified — leave it to ssh
  done
  [ "$n" -gt 0 ] && printf '%s\n' "$scan" >> /root/.ssh/known_hosts && chmod 600 /root/.ssh/known_hosts
}

# GitHub answers a successful key test with exit 1 and a "successfully
# authenticated" line, so the MESSAGE is the test, not the exit code — and the
# output has to be captured first: under `set -o pipefail` a `ssh … | grep -q`
# reports ssh's 1 even when grep matched.
github_auth_ok() {
  local out
  [ -s "$GH_KEY" ] || return 1
  # BatchMode prevents any dialog; a rejected key returns 255, a good one 1 —
  # we therefore never check the exit code, only the verified message.
  out="$(ssh -o BatchMode=yes -o StrictHostKeyChecking=accept-new -T git@github.com 2>&1)" || true
  printf '%s' "$out" | grep -q "successfully authenticated"
}

# The push IS the collaborator check: the authenticated key proves only WHICH
# GitHub account it belongs to; GitHub itself rejects a push from an account
# that may not write here, and that rejection is reported as an error. Runs
# only in the installer's tail (after a green smoke), never as a pre-check.
#
# NOTE (AGENTS rule 3): raw git is normally reserved for the make recipes — the
# one exception is right here, because the installer must push to a TEMPORARY
# remote with --no-verify (the pre-push hook's live smoke cannot pass before the
# stack exists, and the installer has already run smoke itself).
github_push() {
  [ "${GH_REMOTE:-false}" = "true" ] || return 0
  if [ -z "${GITHUB_USER:-}" ] || [ "${GITHUB_USER:-}" = "exampleuser" ]; then
    warn github_push "cannot tell which account to push to — no origin remote and no GITHUB_USER in $DATA/instance.conf"
    return 1
  fi
  # Identity is required (collected up front); no root fallback, no blank skip.
  if [ -z "${GITHUB_COMMIT_NAME:-}" ] || [ -z "${GITHUB_COMMIT_EMAIL:-}" ]; then
    warn github_push "no Git commit identity — cannot push (re-run the installer and enter name + email)"
    return 1
  fi
  # GitHub is opt-in, so a requested push that CANNOT run is a failure, not a
  # skip: an unauthorized key must not fall through to a success block.
  if ! github_auth_ok; then
    warn github_push "GitHub key is not authorized (ssh -T git@github.com failed) — push skipped"
    return 1
  fi
  export GIT_COMMITTER_NAME="$GITHUB_COMMIT_NAME" GIT_COMMITTER_EMAIL="$GITHUB_COMMIT_EMAIL" \
         GIT_AUTHOR_NAME="$GITHUB_COMMIT_NAME" GIT_AUTHOR_EMAIL="$GITHUB_COMMIT_EMAIL"
  local url="git@github.com:$GITHUB_USER/$REPO_NAME.git"

  # Idempotent by construction: the push itself creates no persistent remote.
  # `temppush` is a one-shot URL remote — added, pushed, removed — and it is
  # removed BEFORE the push (run both steps, then clean up on every exit path),
  # so a re-run after an abort finds nothing stale to collide with. Git with no
  # origin falls back to the COMMAND-LINE url, which is what a clone whose
  # origin was never set needs; origin is separately pointed at the SSH URL by
  # github_set_origin once the key is authorized (so the operator can push
  # without a login). Every piece of identity is passed with `-c`, so the run
  # does not write shared repo config.
  git -C "$REPO" remote remove temppush 2>/dev/null || true
  local push_out rc
  push_out="$(git -C "$REPO" -c user.name="$GITHUB_COMMIT_NAME" -c user.email="$GITHUB_COMMIT_EMAIL" \
                -c remote.temppush.url="$url" \
                push --no-verify temppush HEAD 2>&1)"
  rc=$?
  git -C "$REPO" remote remove temppush 2>/dev/null || true
  printf '%s\n' "$push_out" >>"$LOG"
  if [ $rc -eq 0 ]; then
    detail "  GitHub: pushed to $url"
    return 0
  fi
  if printf '%s' "$push_out" | grep -q 'fetch first'; then
    warn github_push "push rejected — local history diverged from the remote (fetch first); run 'make fetch' or 'git pull --rebase' and re-run the installer"
  else
    warn github_push "push rejected — $url refused $GITHUB_USER (not a collaborator, or the key is not authorized)"
  fi
  return 1
}

# Point origin at the SSH URL once the GitHub key is authorized, so the OPERATOR
# can `git push` themselves with no GitHub login (this host has no HTTPS token).
# The installer's own push is a one-shot `temppush` URL remote and does not need
# origin — but the success block and any later manual push do, and origin stayed
# HTTPS while the push was rejected, leaving `git push` to prompt for a username
# (observed 2026-10-15). Only ever after authorization, so a non-collaborator's
# HTTPS origin is never rewritten.
github_set_origin() {
  local want="git@github.com:$GITHUB_USER/$REPO_NAME.git" cur
  cur="$(git -C "$REPO" remote get-url origin 2>/dev/null || true)"
  [ "$cur" = "$want" ] && return 0
  git -C "$REPO" remote set-url origin "$want" 2>/dev/null \
    || git -C "$REPO" remote add origin "$want" 2>/dev/null || return 0
  detail "  origin set to $want (push without a GitHub login)"
}

github_access() {
  [ "${GH_REMOTE:-false}" = "true" ] || { log "  GitHub remote access: not requested — skipped"; return 0; }
  if [ -z "${GITHUB_USER:-}" ] || [ "${GITHUB_USER:-}" = "exampleuser" ]; then
    fail github_auth "cannot tell which account to push to — no origin remote and no GITHUB_USER in $DATA/instance.conf"
    return
  fi
  github_keygen || { fail github_key; return; }
  github_known_hosts
  # Resume shortcut: the key file survives across reboots/reinstalls, so an
  # already-authorized key skips the wait entirely (authorizing once keeps us
  # logged in for the life of the key pair).
  if [ -s "$GH_KEY" ] && github_auth_ok; then
    GH_AUTH_OK=1
    github_set_origin
    detail "  GitHub key authorized (ssh -T git@github.com) — the push runs at the end"
    save_state
    return
  fi
  # Not authorized yet: print the public key, then verify it AUTOMATICALLY —
  # poll ssh until GitHub accepts it. No manual "press Enter to re-check" step;
  # Ctrl-C aborts the installer.
  printf '\n %s── Github SSH Key Prompt %s────────────────────────────────────────%s\n' "$C_GREEN" "$C_GREY" "$C_RST"
  printf '  %sPaste this public key once — the installer verifies it automatically.%s\n' "$C_GREY" "$C_RST"
  printf '  GitHub → Settings → SSH and GPG keys → New SSH key → paste this line:\n\n'
  printf '    %s\n\n' "$(cat "$GH_KEY.pub")"
  printf '  %sSettings is under the avatar menu (top right); "New SSH key" is the%s\n' "$C_GREY" "$C_RST"
  printf '  %sgreen button in the SSH keys box — name it after this host.%s\n' "$C_GREY" "$C_RST"
  printf ' %s─────────────────────────────────────────────────────────────────────%s\n\n' "$C_GREY" "$C_RST"
  local _waited=0
  until github_auth_ok; do
    sleep 5
    _waited=$(( _waited + 5 ))
    [ $(( _waited % 15 )) -eq 0 ] && log "  GitHub: key not authorized yet (${_waited}s) — paste the line above; verification is automatic."
  done
  GH_AUTH_OK=1
  github_set_origin
  save_state
  detail "  GitHub key authorized (ssh -T git@github.com) — the push runs at the end"
}

